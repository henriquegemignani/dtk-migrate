//! Assigning target address ranges to source translation units.
//!
//! This stage answers the weakest of the four questions a migration can ask:
//! *which source file owns this range of the target?* A right answer lets the
//! comparison pair up functions that were already correct and merely
//! unattributed. It says nothing about whether that file compiles, and the
//! stage is careful never to imply otherwise: the candidate's source object
//! stays disabled throughout, and acceptance deliberately does not require any
//! gain in matched code.
//!
//! What it does require is that the range is not somebody else's, that the
//! build still produces retail bytes, that the unit is still linked from its
//! extracted original rather than from source, and that no existing unit lost
//! ground. Those are the things a wrong range would break.

