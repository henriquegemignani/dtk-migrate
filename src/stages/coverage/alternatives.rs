fn exact_anchor_eligible(
    unit: &CoverageUnit,
    anchor: &CoverageAnchor,
    observations: &ObservationIndex,
) -> bool {
    let (Some(start), Some(end)) =
        (parse_address(&anchor.target_address), parse_address(&anchor.target_end))
    else {
        return false;
    };
    let owned_elsewhere = anchor
        .existing_target_owner
        .as_deref()
        .is_some_and(|owner| owner != unit.name && !anchor.existing_owner_autogenerated);
    let observed = observations.at_target("main", &anchor.section, start);
    anchor.size >= MIN_ANCHOR_BYTES
        && end > start
        && end - start == anchor.size
        && !anchor.source_weak
        && !anchor.target_weak
        && anchor.source_extent_known
        && anchor.target_extent_known
        && anchor.source_unit_explicit
        && anchor.source_unit_wholly_owned
        && !anchor.template_instantiation
        && anchor.unique_source
        && anchor.unique_target
        && anchor.normalized_body_equal
        && anchor.relocation_layout_equal
        && anchor.required_alignment != 0
        && start % anchor.required_alignment == 0
        && end % anchor.required_alignment == 0
        && !owned_elsewhere
        && observed.is_some_and(|item| {
            item.source.unit == unit.name
                && item.source.name == anchor.source_name
                && parse_address(&item.source.address) == parse_address(&anchor.source_address)
                && parse_address(&item.target.end) == Some(end)
                && item.independent
        })
}

fn layout_anchor_eligible(
    unit: &CoverageUnit,
    anchor: &LayoutShiftAnchor,
    observations: &ObservationIndex,
) -> bool {
    let (Some(start), Some(end)) =
        (parse_address(&anchor.target_address), parse_address(&anchor.target_end))
    else {
        return false;
    };
    let owned_elsewhere = anchor
        .existing_target_owner
        .as_deref()
        .is_some_and(|owner| owner != unit.name && !anchor.existing_owner_autogenerated);
    let observed = observations.at_target("main", &anchor.section, start);
    end > start
        && end - start == anchor.size
        && !anchor.source_weak
        && !anchor.target_weak
        && anchor.source_extent_known
        && anchor.target_extent_known
        && anchor.source_unit_explicit
        && anchor.source_unit_wholly_owned
        && !anchor.template_instantiation
        && anchor.unique_source
        && anchor.unique_target
        && anchor.layout_masked_body_equal
        && anchor.relocation_layout_equal
        && anchor.this_accesses > 0
        && anchor.changed_this_accesses > 0
        && !anchor.offset_deltas.is_empty()
        && anchor.required_alignment != 0
        && start % anchor.required_alignment == 0
        && end % anchor.required_alignment == 0
        && !owned_elsewhere
        && observed.is_some_and(|item| {
            item.source.unit == unit.name
                && item.source.name == anchor.source_name
                && parse_address(&item.source.address) == parse_address(&anchor.source_address)
                && parse_address(&item.target.end) == Some(end)
                && !item.ambiguous
        })
}

/// Tiers a matched function may carry. Anything else is not a match this
/// evidence understands.
const MATCH_TIERS: [&str; 3] = ["confident", "probable", "candidate"];
/// Tiers strong enough to count toward a policy minimum.
const STRONG_TIERS: [&str; 2] = ["confident", "probable"];

/// What a generator says a neighbour gives up: one contiguous range narrowed
/// at one end. Only generation reads this; it becomes the neighbour's complete
/// after-body in the transaction, which is what is applied and checked.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct OwnerRevision {
    pub unit: String,
    pub section: String,
    pub original_start: String,
    pub original_end: String,
    pub revised_start: String,
    pub revised_end: String,
}

/// One complete way a unit could claim a target range.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct Alternative {
    /// The identity of `transaction`, which is what a worker and the
    /// coordinator agree on and what a selection records.
    pub id: String,
    pub evidence: String,
    pub support_group: Option<String>,
    pub section: String,
    pub start: String,
    pub end: String,
    pub covered_bytes: u32,
    /// Bytes the unit would own that it does not own already. For a unit with
    /// no block this is the whole claim; for one being extended it is only the
    /// new ground, which is what a build actually buys. A metric, not a gate.
    #[serde(default)]
    pub gained_bytes: u32,
    /// The candidate unit's complete body after the transaction, repeated from
    /// it so that readers of the candidate's own proposal need not dig.
    pub lines: Vec<String>,
    /// The evidence records behind it, kept as written so the run's report can
    /// show exactly what was believed.
    pub anchors: Vec<serde_json::Value>,
    /// Address-level certificate for the candidate's complete body. This is
    /// recomputed from the canonical observation index before trial and again
    /// before publication; it is recorded here for diagnosis and ranking.
    #[serde(default)]
    pub ownership: OwnershipAssessment,
    /// The same certificate for every *other* unit the transaction gives
    /// ground to. Units that only give ground up have nothing to certify: the
    /// transaction names who receives each address they lose.
    #[serde(default, skip_serializing_if = "BTreeMap::is_empty")]
    pub receiver_ownership: BTreeMap<String, OwnershipAssessment>,
    /// The two edges of the range the candidate holds in this section once the
    /// transaction applies, as the observations judge them. Diagnostic, and a
    /// ranking key between otherwise equally attributed claims.
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub boundaries: Vec<EdgeHypothesis>,
    /// Everything that applying this alternative changes, with its exact
    /// preconditions. The only thing ever applied.
    pub transaction: OwnershipTransaction,
}

impl Alternative {
    /// An alternative for a hand-written complete body, derived against
    /// `blocks` but neither previewed nor certified. For tools and tests that
    /// need to apply a specific change the way a trial would.
    pub fn uncertified(
        unit: &str,
        claim: (&str, u32, u32),
        lines: Vec<String>,
        others: Vec<(String, Vec<String>)>,
        blocks: &Blocks,
    ) -> Result<Self> {
        let (section, start, end) = claim;
        let transaction = OwnershipTransaction::build(
            blocks,
            std::iter::once((unit.to_string(), lines.clone())).chain(others),
            Provenance {
                policy: policy_digest(),
                observation_sha256: String::new(),
                evidence: vec!["uncertified".into()],
                ..Default::default()
            },
        )?;
        Ok(Self {
            id: transaction.id.clone(),
            evidence: "uncertified".into(),
            support_group: None,
            section: section.into(),
            start: format_address(start),
            end: format_address(end),
            covered_bytes: end - start,
            gained_bytes: transaction.gained_bytes(unit),
            lines,
            anchors: Vec::new(),
            ownership: OwnershipAssessment::default(),
            receiver_ownership: BTreeMap::new(),
            boundaries: Vec::new(),
            transaction,
        })
    }

    /// How many of the resulting range's two edges the observations support.
    pub fn supported_boundaries(&self) -> u32 {
        self.boundaries.iter().filter(|edge| edge.supported).count() as u32
    }

    /// Whether both edges of the resulting range are supported: a boundary
    /// finished at both ends, which is what a composition exists to produce.
    ///
    /// Only both edges count. A range with one supported edge is still an
    /// unfinished claim, and preferring it would let a small fragment that
    /// happens to touch a foreign function outrank a much larger claim with
    /// more corroborated members. The certificate's own edge count is no
    /// substitute: it credits a range only when it equals the envelope of the
    /// unit's attributed members, which never includes a helper nothing
    /// matched.
    fn finished_boundary(&self) -> bool { self.supported_boundaries() == 2 }
}

/// What a generator proposes, before it is a transaction.
#[derive(Debug, Clone)]
struct Draft {
    evidence: String,
    support_group: Option<String>,
    section: String,
    start: u32,
    end: u32,
    anchors: Vec<serde_json::Value>,
    owner_revisions: Vec<OwnerRevision>,
    /// For a composed claim, the families behind its left and right edges.
    /// Any other draft's edges are both its own.
    edge_families: Option<(Vec<String>, Vec<String>)>,
}

impl Draft {
    fn family(&self) -> String {
        match &self.support_group {
            Some(group) => format!("{}:{group}", self.evidence),
            None => self.evidence.clone(),
        }
    }
}

/// A digest of the coverage policy a transaction was derived under.
pub fn policy_digest() -> String {
    let policy = serde_json::to_vec(&current_policy()).unwrap_or_default();
    format!("coverage/{:x}", Sha256::digest(policy))
}

pub fn parse_address(text: &str) -> Option<u32> {
    let digits = text.strip_prefix("0x").or_else(|| text.strip_prefix("0X")).unwrap_or(text);
    u32::from_str_radix(digits, 16).ok()
}

pub fn format_address(value: u32) -> String { format!("0x{value:08X}") }

#[cfg(test)]
fn split_line(section: &str, start: u32, end: u32) -> String {
    format!("\t{section:11} start:0x{start:08X} end:0x{end:08X}")
}

fn alternative(
    section: &str,
    start: u32,
    end: u32,
    anchors: Vec<serde_json::Value>,
    evidence: &str,
    group: Option<String>,
    owner_revisions: Vec<OwnerRevision>,
) -> Draft {
    Draft {
        evidence: evidence.to_string(),
        support_group: group,
        section: section.to_string(),
        start,
        end,
        anchors,
        owner_revisions,
        edge_families: None,
    }
}

type Blocks = IndexMap<String, Vec<String>>;

/// Whether the range is ground some *other* unit already claims.
///
/// A unit's own block is not an obstacle to its own boundary moving — that is
/// the whole of what refining a split means. Every other unit's is.
fn overlaps_other(unit: &str, section: &str, start: u32, end: u32, blocks: &Blocks) -> bool {
    blocks
        .iter()
        .filter(|(name, _)| name.as_str() != unit)
        .flat_map(|(_, lines)| lines)
        .filter_map(|line| parse_range(line))
        .any(|range| range.section == section && start < range.end && range.start < end)
}

/// Total bytes a body claims, across every section.
pub fn body_bytes(lines: &[String]) -> u32 {
    lines.iter().filter_map(|line| parse_range(line)).map(|range| range.size()).sum()
}

/// The complete body a unit would have if it also claimed `start..end`.
///
/// Applying an alternative replaces the unit's block outright, so the body has
/// to carry everything the unit keeps: its other sections verbatim, and this
/// section's range enlarged rather than overwritten.
///
/// `None` when the claim cannot be justified as part of this unit. A range
/// disconnected from what the unit already owns in that section is a second
/// fragment, not a boundary moving, and spanning from the lowest start to the
/// highest end would swallow everything in between on no evidence at all.
fn complete_body(existing: &[String], section: &str, start: u32, end: u32) -> Option<Vec<String>> {
    // Each range keeps the attribute text it was written with. The claim
    // itself has none of its own; a range it merges into lends it its.
    let mut here: Vec<(u32, u32, Option<String>)> = Vec::new();
    let mut elsewhere: Vec<String> = Vec::new();
    let mut insert_at: Option<usize> = None;
    for line in existing {
        match parse_range(line) {
            Some(range) if range.section == section => {
                insert_at.get_or_insert(elsewhere.len());
                here.push((range.start, range.end, Some(entry_suffix(line))));
            }
            // Anything else is another section, or a line this parser does not
            // claim to understand; either way it is kept exactly as found.
            _ => elsewhere.push(line.clone()),
        }
    }
    // Touching counts: a tail that begins where the split ends is the same
    // range continuing, not a fragment somewhere else.
    if !here.is_empty() && !here.iter().any(|&(a, b, _)| start <= b && a <= end) {
        return None;
    }

    here.push((start, end, None));
    here.sort_unstable();
    let mut ranges: Vec<(u32, u32, Option<String>)> = Vec::with_capacity(here.len());
    for (a, b, suffix) in here {
        match ranges.last_mut() {
            Some(last) if a <= last.1 => {
                last.1 = last.1.max(b);
                match (&last.2, suffix) {
                    (_, None) => {}
                    (None, Some(suffix)) => last.2 = Some(suffix),
                    // Two ranges written differently cannot become one line
                    // without deciding which of them was wrong.
                    (Some(kept), Some(suffix)) if *kept != suffix => return None,
                    _ => {}
                }
            }
            _ => ranges.push((a, b, suffix)),
        }
    }

    let at = insert_at.unwrap_or(elsewhere.len());
    let mut lines = elsewhere;
    for (offset, (a, b, suffix)) in ranges.into_iter().enumerate() {
        lines.insert(at + offset, entry_line(section, a, b, suffix.as_deref().unwrap_or("")));
    }
    Some(lines)
}

/// The body `revision.unit` keeps once it gives up what the revision says.
///
/// A revision may only narrow one exactly-held range at one or both ends,
/// never move or widen it, and the range keeps its attributes.
fn revised_body(blocks: &Blocks, revision: &OwnerRevision) -> Option<Vec<String>> {
    let original_start = parse_address(&revision.original_start)?;
    let original_end = parse_address(&revision.original_end)?;
    let revised_start = parse_address(&revision.revised_start)?;
    let revised_end = parse_address(&revision.revised_end)?;
    if revised_end <= revised_start
        || original_end <= original_start
        || revised_start < original_start
        || revised_end > original_end
        || (revised_start == original_start && revised_end == original_end)
        || single_section_range(blocks, &revision.unit, &revision.section)
            != Some((original_start, original_end))
    {
        return None;
    }
    let body = blocks.get(&revision.unit)?;
    let matching: Vec<usize> = body
        .iter()
        .enumerate()
        .filter(|(_, line)| {
            parse_range(line).is_some_and(|range| {
                range.section == revision.section
                    && range.start == original_start
                    && range.end == original_end
            })
        })
        .map(|(index, _)| index)
        .collect();
    let [index] = matching[..] else { return None };
    let mut revised = body.clone();
    revised[index] =
        entry_line(&revision.section, revised_start, revised_end, &entry_suffix(&body[index]));
    Some(revised)
}

/// What a draft is judged against: the unit, the world, the observations and
/// the extracts the unit's source requires.
struct Setting<'a> {
    unit: &'a str,
    blocks: &'a Blocks,
    observations: &'a ObservationIndex,
    required_extracts: &'a [crate::analysis::coverage::RequiredExtract],
    policy: String,
}

fn section_ranges(lines: &[String]) -> BTreeMap<String, Vec<(u32, u32)>> {
    let mut ranges: BTreeMap<String, Vec<(u32, u32)>> = BTreeMap::new();
    for range in lines.iter().filter_map(|line| parse_range(line)) {
        ranges.entry(range.section).or_default().push((range.start, range.end));
    }
    ranges
}

/// The certificate for `unit` taking the body a transaction gives it.
pub fn assess_member(
    observations: &ObservationIndex,
    transaction: &OwnershipTransaction,
    unit: &str,
) -> Option<OwnershipAssessment> {
    let member = transaction.member(unit)?;
    let before = section_ranges(member.before.as_deref().unwrap_or_default());
    let after = section_ranges(&member.after);
    Some(observations.assess(unit, MODULE, &before, &after))
}

/// Turns a draft into an offered alternative, or explains nothing and drops
/// it: an incomplete body, a transaction the current splits refuse, or a
/// receiver whose new ground the observations do not support.
fn finish(draft: Draft, setting: &Setting) -> Option<Alternative> {
    let unit = setting.unit;
    let existing = setting.blocks.get(unit).map(Vec::as_slice).unwrap_or_default();
    let lines = complete_body(existing, &draft.section, draft.start, draft.end)?;
    let mut changes = vec![(unit.to_string(), lines.clone())];
    for revision in &draft.owner_revisions {
        changes.push((revision.unit.clone(), revised_body(setting.blocks, revision)?));
    }

    // Build the transaction first with only the generator's evidence, to
    // learn which members it has, then certify each receiver and cite the
    // attributions that certificate rests on.
    let provisional = OwnershipTransaction::build(setting.blocks, changes.clone(), Provenance {
        policy: setting.policy.clone(),
        observation_sha256: setting.observations.digest().to_string(),
        evidence: vec!["provisional".into()],
        ..Default::default()
    })
    .ok()?;
    // A claim the unit already covers is not a refinement, and offering it
    // would have the stage rebuild the project to learn nothing.
    provisional.member(unit)?;

    let ownership = assess_member(setting.observations, &provisional, unit)?;
    if !ownership.permits_automatic_claim() {
        return None;
    }
    let mut receiver_ownership = BTreeMap::new();
    for receiver in provisional.receivers().into_iter().filter(|receiver| *receiver != unit) {
        let assessment = assess_member(setting.observations, &provisional, receiver)?;
        if !assessment.permits_automatic_claim() {
            return None;
        }
        receiver_ownership.insert(receiver.to_string(), assessment);
    }

    let mut evidence =
        vec![format!("{}:{}", draft.evidence, draft.support_group.as_deref().unwrap_or(""))];
    evidence.extend(
        std::iter::once(&ownership)
            .chain(receiver_ownership.values())
            .flat_map(|assessment| &assessment.records)
            .filter(|record| record.class == ClaimClass::IndependentlyAttributed)
            .filter_map(|record| record.attribution_id.clone()),
    );
    let transaction = OwnershipTransaction::build(setting.blocks, changes, Provenance {
        policy: setting.policy.clone(),
        observation_sha256: setting.observations.digest().to_string(),
        evidence,
        required_extracts: setting.required_extracts.to_vec(),
        releases: Vec::new(),
    })
    .ok()?;
    // The same checks a trial will make, made now, so that nothing is offered
    // which could only ever be refused.
    transaction.preview(setting.blocks).ok()?;
    let boundaries = judge_edges(&draft, &lines, setting);

    Some(Alternative {
        id: transaction.id.clone(),
        evidence: draft.evidence,
        support_group: draft.support_group,
        section: draft.section,
        start: format_address(draft.start),
        end: format_address(draft.end),
        covered_bytes: draft.end - draft.start,
        gained_bytes: transaction.gained_bytes(unit),
        lines,
        anchors: draft.anchors,
        ownership,
        receiver_ownership,
        boundaries,
        transaction,
    })
}

/// Names, on every judged edge, the other supported addresses the unit's
/// alternatives place on the same side of the same section. A supported edge
/// with a rival is one the evidence has not settled.
fn record_competing_edges(alternatives: &mut [Alternative]) {
    let supported: BTreeSet<(String, Side, String)> = alternatives
        .iter()
        .flat_map(|alternative| &alternative.boundaries)
        .filter(|edge| edge.supported)
        .map(|edge| (edge.section.clone(), edge.side, edge.address.clone()))
        .collect();
    for edge in alternatives.iter_mut().flat_map(|alternative| &mut alternative.boundaries) {
        edge.competing = supported
            .iter()
            .filter(|(section, side, address)| {
                *section == edge.section && *side == edge.side && *address != edge.address
            })
            .map(|(_, _, address)| address.clone())
            .collect();
    }
}

/// Both edges of the range in `lines` that contains the draft's claim.
fn judge_edges(draft: &Draft, lines: &[String], setting: &Setting) -> Vec<EdgeHypothesis> {
    let Some(range) = lines.iter().filter_map(|line| parse_range(line)).find(|range| {
        range.section == draft.section && range.start <= draft.start && draft.end <= range.end
    }) else {
        return Vec::new();
    };
    let (left, right) =
        draft.edge_families.clone().unwrap_or_else(|| (vec![draft.family()], vec![draft.family()]));
    // An edge the claim did not move is still the unit's edge, but none of
    // this draft's families proposed it.
    let families = |address: u32, moved: u32, families: Vec<String>| {
        if address == moved { families } else { Vec::new() }
    };
    vec![
        boundaries::judge(
            setting.observations,
            setting.unit,
            MODULE,
            &draft.section,
            Side::Left,
            range.start,
            families(range.start, draft.start, left),
        ),
        boundaries::judge(
            setting.observations,
            setting.unit,
            MODULE,
            &draft.section,
            Side::Right,
            range.end,
            families(range.end, draft.end, right),
        ),
    ]
}

/// The one range a unit claims in a section, when it claims exactly one.
fn single_section_range(blocks: &Blocks, unit: &str, section: &str) -> Option<(u32, u32)> {
    let mut ranges = blocks
        .get(unit)?
        .iter()
        .filter_map(|line| parse_range(line))
        .filter(|range| range.section == section);
    let first = ranges.next()?;
    ranges.next().is_none().then_some((first.start, first.end))
}

fn relative_size_delta(source_bytes: u32, target_bytes: u32) -> f32 {
    let base = source_bytes.max(target_bytes);
    if base == 0 { 0.0 } else { source_bytes.abs_diff(target_bytes) as f32 / base as f32 }
}

fn alignment_margin(best: f32, second: f32) -> f32 {
    if best <= 0.0 { 0.0 } else { (best - second).max(0.0) / best }
}

fn strong_count<'a>(tiers: impl Iterator<Item = &'a str>) -> u32 {
    tiers.filter(|tier| STRONG_TIERS.contains(tier)).count() as u32
}

/// Checks a run of matched functions is a usable ordered sequence, returning
/// its target ranges and how many matches are strong.
///
/// The requirements are what make a sequence evidence at all: every function is
/// a primary match of a known tier, the source addresses ascend without
/// repeating, each target range is non-empty and exactly its stated size, and
/// the ranges do not overlap.
fn sequence_details(functions: &[SequenceFunction]) -> Option<(Vec<(u32, u32)>, u32)> {
    let mut source_addresses = Vec::with_capacity(functions.len());
    let mut ranges = Vec::with_capacity(functions.len());
    for function in functions {
        source_addresses.push(parse_address(&function.source_address)?);
        let start = parse_address(&function.target_address)?;
        let end = parse_address(&function.target_end)?;
        if end <= start || end - start != function.size {
            return None;
        }
        ranges.push((start, end));
    }
    if functions.iter().any(|f| !MATCH_TIERS.contains(&f.tier.as_str()))
        || functions.iter().any(|f| !f.primary)
        || !source_addresses.windows(2).all(|pair| pair[0] < pair[1])
        || ranges.windows(2).any(|pair| pair[0].1 > pair[1].0)
    {
        return None;
    }
    Some((ranges, strong_count(functions.iter().map(|f| f.tier.as_str()))))
}

fn sequence_is_observed(
    unit: &str,
    section: &str,
    functions: &[SequenceFunction],
    observations: &ObservationIndex,
) -> bool {
    functions.iter().all(|function| {
        let Some(target) = parse_address(&function.target_address) else { return false };
        observations.at_target("main", section, target).is_some_and(|item| {
            item.source.unit == unit
                && item.source.name == function.source_name
                && parse_address(&item.source.address) == parse_address(&function.source_address)
                && parse_address(&item.target.end) == parse_address(&function.target_end)
                && item.tier.as_str() == function.tier
                && !item.ambiguous
        })
    })
}

/// Whether the given function and helper ranges tile `start..end` exactly, with
/// no gap and no overlap.
fn partition_covers(
    start: u32,
    end: u32,
    function_ranges: &[(u32, u32)],
    helpers: &[GapHelper],
) -> bool {
    let mut pieces = function_ranges.to_vec();
    for helper in helpers {
        let (Some(left), Some(right)) =
            (parse_address(&helper.target_address), parse_address(&helper.target_end))
        else {
            return false;
        };
        if right.saturating_sub(left) != helper.size {
            return false;
        }
        pieces.push((left, right));
    }
    pieces.sort();
    !pieces.is_empty()
        && pieces[0].0 == start
        && pieces[pieces.len() - 1].1 == end
        && pieces.iter().all(|(left, right)| right > left)
        && pieces.windows(2).all(|pair| pair[0].1 == pair[1].0)
}

/// How many exact-body anchors of this unit sit wholly inside a range and meet
/// every strictness the policy asks of an anchor.
///
/// This is the independent corroboration an ownership transfer needs: the
/// sequence says where the unit's functions line up, and these say that some of
/// them are byte-identical in a way nothing else could claim.
fn direct_anchor_count(
    unit: &CoverageUnit,
    section: &str,
    start: u32,
    end: u32,
    owner: &str,
    observations: &ObservationIndex,
) -> u32 {
    unit.anchors
        .iter()
        .filter(|anchor| {
            let (Some(anchor_start), Some(anchor_end)) =
                (parse_address(&anchor.target_address), parse_address(&anchor.target_end))
            else {
                return false;
            };
            let owned_elsewhere = match &anchor.existing_target_owner {
                None => false,
                Some(existing) => {
                    existing != &unit.name
                        && existing != owner
                        && !anchor.existing_owner_autogenerated
                }
            };
            anchor.section == section
                && start <= anchor_start
                && anchor_start < anchor_end
                && anchor_end <= end
                && anchor_end - anchor_start == anchor.size
                && anchor.size >= MIN_SEQUENCE_ANCHOR_BYTES
                && !anchor.source_weak
                && !anchor.target_weak
                && anchor.source_extent_known
                && anchor.target_extent_known
                && anchor.source_unit_explicit
                && anchor.source_unit_wholly_owned
                && !anchor.template_instantiation
                && anchor.unique_source
                && anchor.unique_target
                && anchor.normalized_body_equal
                && anchor.relocation_layout_equal
                && !owned_elsewhere
                && observations.at_target("main", section, anchor_start).is_some_and(|item| {
                    item.source.unit == unit.name
                        && item.source.name == anchor.source_name
                        && parse_address(&item.source.address)
                            == parse_address(&anchor.source_address)
                        && parse_address(&item.target.end) == Some(anchor_end)
                        && item.independent
                })
        })
        .count() as u32
}

fn value(item: &impl Serialize) -> serde_json::Value {
    serde_json::to_value(item).unwrap_or(serde_json::Value::Null)
}

/// Adds the section a sequence function belongs to, which the function record
/// itself does not carry.
fn anchor_value(function: &SequenceFunction, section: &str) -> serde_json::Value {
    let mut item = value(function);
    if let Some(object) = item.as_object_mut() {
        object.insert("section".into(), serde_json::Value::String(section.to_string()));
    }
    item
}

fn sort_alternatives(alternatives: &mut [Alternative]) {
    alternatives.sort_by(|a, b| {
        b.ownership
            .complete_membership
            .cmp(&a.ownership.complete_membership)
            .then_with(|| b.finished_boundary().cmp(&a.finished_boundary()))
            .then_with(|| b.ownership.supported_edges.cmp(&a.ownership.supported_edges))
            .then_with(|| b.ownership.independent_members.cmp(&a.ownership.independent_members))
            .then_with(|| a.ownership.padding_bytes.cmp(&b.ownership.padding_bytes))
            .then_with(|| b.transaction.members.len().cmp(&a.transaction.members.len()))
            .then_with(|| b.gained_bytes.cmp(&a.gained_bytes))
            .then_with(|| parse_address(&a.start).cmp(&parse_address(&b.start)))
    });
}

/// Combine individual and joint proposals under the same ranking rule.
pub fn add_joint(alternatives: &mut Vec<Alternative>, joint: Vec<Alternative>) {
    alternatives.extend(joint);
    alternatives.sort_by(|a, b| a.id.cmp(&b.id));
    alternatives.dedup_by(|a, b| a.id == b.id);
    record_competing_edges(alternatives);
    sort_alternatives(alternatives);
}

