//! A shared helper is placed only when *every* compiled copy has an
//! independently anchored, different retail occurrence.

use std::collections::BTreeSet;

use dtk_migrate::analysis::{
    matching::{MatchMethod, MatchTier},
    object_evidence::{
        BuildFreshness, CompiledDefinition, CompiledFunction, CompiledReference, ObjectEvidence,
        ObjectRecord, ObjectStatus, ScanStatus, TargetFunctionReferences,
        emitted_owner_resolutions, order_matches, relocation_placements,
    },
    ownership::{
        AttributionOrigin, FunctionAttribution, FunctionLocation, IdentificationReport,
        ObservationIndex, SourceFunction, SourceFunctionObservation, TargetFunctionObservation,
        UnitIdentification,
    },
};
use sha2::{Digest, Sha256};

fn function(name: &str, start: &str, end: &str, hash: char, weak: bool) -> CompiledFunction {
    CompiledFunction {
        name: name.into(),
        section: ".text".into(),
        address: start.into(),
        end: end.into(),
        normalized_body_sha256: Some(hash.to_string().repeat(64)),
        weak,
        references: Vec::new(),
    }
}

fn target(name: &str, start: &str, end: &str, hash: char) -> TargetFunctionObservation {
    TargetFunctionObservation {
        name: name.into(),
        module: "main".into(),
        section: ".text".into(),
        address: start.into(),
        end: end.into(),
        current_owner: None,
        owner_autogenerated: false,
        callers: Vec::new(),
        normalized_body_sha256: Some(hash.to_string().repeat(64)),
        weak: name == "helper",
    }
}

fn anchor(unit: &str, name: &str, start: &str, end: &str) -> FunctionAttribution {
    FunctionAttribution {
        id: format!("{unit}:{name}"),
        target: FunctionLocation {
            module: "main".into(),
            section: ".text".into(),
            address: start.into(),
            end: end.into(),
        },
        source: SourceFunction {
            name: name.into(),
            unit: unit.into(),
            module: "main".into(),
            section: ".text".into(),
            address: start.into(),
            end: end.into(),
        },
        method: MatchMethod::ExactHash,
        tier: MatchTier::Confident,
        confidence: 1.0,
        evidence_count: 1,
        origin: AttributionOrigin::NormalizedBody,
        distinctive_body: true,
        unique_exact_body: true,
        binary_supported: true,
        independent: true,
        ambiguous: false,
        competing: None,
        source_weak: false,
        target_weak: false,
        template_instantiation: false,
        current_target_owner: None,
        evidence: Vec::new(),
    }
}

fn fixture() -> (
    ObjectEvidence,
    BTreeSet<String>,
    Vec<SourceFunctionObservation>,
    Vec<TargetFunctionObservation>,
    Vec<FunctionAttribution>,
) {
    let units = BTreeSet::from(["A.cpp".into(), "B.cpp".into()]);
    let mut objects = Vec::new();
    let mut definitions = Vec::new();
    let mut targets = Vec::new();
    let mut attributions = Vec::new();
    let mut target_references = Vec::new();
    for (unit, prefix, object_hash, target_start, left_hash, right_hash) in
        [("A.cpp", "A", 'b', 0x1000, '1', '2'), ("B.cpp", "B", 'c', 0x2000, '3', '4')]
    {
        let address = |offset: u32| format!("0x{:08X}", target_start + offset);
        let left = format!("{prefix}_left");
        let right = format!("{prefix}_right");
        let object_hash = object_hash.to_string().repeat(64);
        let flags = "-inline deferred".to_string();
        objects.push(ObjectRecord {
            unit: unit.into(),
            base_path: format!("build/PAL/src/{prefix}.o"),
            status: ObjectStatus::Available,
            sha256: Some(object_hash.clone()),
            compiler: Some("mwcc".into()),
            c_flags_sha256: Some(format!("{:x}", Sha256::digest(flags.as_bytes()))),
            c_flags: Some(flags),
            build_freshness: BuildFreshness::Clean,
            functions: vec![
                function(&left, "0x00000000", "0x00000020", left_hash, false),
                function("helper", "0x00000020", "0x00000030", 'a', true),
                function(&right, "0x00000030", "0x00000050", right_hash, false),
            ],
        });
        definitions.push(CompiledDefinition {
            unit: unit.into(),
            name: "helper".into(),
            section: ".text".into(),
            address: "0x00000020".into(),
            end: "0x00000030".into(),
            normalized_body_sha256: "a".repeat(64),
            weak: true,
            object_sha256: object_hash,
        });
        targets.extend([
            target(&left, &address(0), &address(0x20), left_hash),
            target("helper", &address(0x20), &address(0x30), 'a'),
            target(&right, &address(0x30), &address(0x50), right_hash),
        ]);
        attributions.extend([
            anchor(unit, &left, &address(0), &address(0x20)),
            anchor(unit, &right, &address(0x30), &address(0x50)),
        ]);
        target_references.push(TargetFunctionReferences {
            section: ".text".into(),
            address: address(0x20),
            end: address(0x30),
            references: Vec::new(),
        });
    }
    let mut evidence = ObjectEvidence {
        status: ScanStatus::Scanned,
        objdiff_sha256: Some("d".repeat(64)),
        build_graph_sha256: Some("e".repeat(64)),
        target_image_sha256: Some("f".repeat(64)),
        objects,
        unscanned_configured_units: 0,
        unmapped_units: Vec::new(),
        definitions,
        target_references,
        order_matches: Vec::new(),
        relocation_matches: Vec::new(),
        emitted_owners: Vec::new(),
        relocation_placements: Vec::new(),
    };
    evidence.canonicalize(&units, &BTreeSet::from(["a".repeat(64)]), true).unwrap();
    evidence.canonicalize_target_references(&targets).unwrap();
    let source_functions = attributions
        .iter()
        .map(|item| SourceFunctionObservation {
            name: item.source.name.clone(),
            unit: item.source.unit.clone(),
            module: item.source.module.clone(),
            section: item.source.section.clone(),
            address: item.source.address.clone(),
            end: item.source.end.clone(),
            normalized_body_sha256: targets
                .iter()
                .find(|target| target.address == item.target.address)
                .unwrap()
                .normalized_body_sha256
                .clone(),
            weak: false,
        })
        .collect();
    (evidence, units, source_functions, targets, attributions)
}

fn relocation_fixture() -> (
    ObjectEvidence,
    BTreeSet<String>,
    Vec<SourceFunctionObservation>,
    Vec<TargetFunctionObservation>,
    Vec<FunctionAttribution>,
) {
    let (mut evidence, units, source, targets, attributions) = fixture();
    for (index, record) in evidence.objects.iter_mut().enumerate() {
        let target_address = if index == 0 { 0x1000 } else { 0x2000 };
        let endpoint_name = record.functions[0].name.clone();
        record.functions[1].references.push(CompiledReference {
            offset: 4,
            kind: "PpcRel24".into(),
            target: endpoint_name.clone(),
            target_section: Some(".text".into()),
            target_address: 0,
            addend: 0,
        });
        evidence.target_references[index].references.push(CompiledReference {
            offset: 4,
            kind: "PpcRel24".into(),
            target: endpoint_name,
            target_section: Some(".text".into()),
            target_address,
            addend: 0,
        });
    }
    (evidence, units, source, targets, attributions)
}

#[test]
fn two_shared_definitions_have_distinct_independently_placed_retail_copies() {
    let (evidence, units, source, targets, attributions) = fixture();
    let order = order_matches(&evidence, &targets, &attributions);
    assert_eq!(order.len(), 2);
    assert!(order.iter().all(|item| {
        item.before.as_ref().is_some_and(|before| before.independently_attributed)
            && item.after.as_ref().is_some_and(|after| after.independently_attributed)
    }));
    let resolved = emitted_owner_resolutions(&evidence, &units, &source, &targets, &attributions);
    assert_eq!(resolved.len(), 2);
    assert_eq!(resolved[0].unit, "A.cpp");
    assert_eq!(resolved[0].target_address, "0x00001020");
    assert_eq!(resolved[0].excluded_competitors, ["B.cpp"]);
    assert_eq!(resolved[1].unit, "B.cpp");
    assert_eq!(resolved[1].target_address, "0x00002020");
    assert_eq!(resolved[1].excluded_competitors, ["A.cpp"]);
}

#[test]
fn a_competitor_without_two_independent_anchors_is_not_ruled_out() {
    let (evidence, units, source, targets, mut attributions) = fixture();
    attributions.retain(|item| item.id != "B.cpp:B_right");
    assert!(
        emitted_owner_resolutions(&evidence, &units, &source, &targets, &attributions).is_empty()
    );
}

#[test]
fn a_serialized_independent_flag_cannot_replace_unique_body_evidence() {
    let (evidence, units, mut source, targets, attributions) = fixture();
    let mut duplicate = source[0].clone();
    duplicate.unit = "B.cpp".into();
    duplicate.address = "0x00004000".into();
    duplicate.end = "0x00004020".into();
    source.push(duplicate);
    assert!(
        emitted_owner_resolutions(&evidence, &units, &source, &targets, &attributions).is_empty()
    );
}

#[test]
fn incomplete_or_stale_objects_and_surplus_target_copies_do_not_prove_emission() {
    let (mut evidence, units, source, mut targets, attributions) = fixture();
    evidence.objects[1].build_freshness = BuildFreshness::Dirty;
    assert!(
        emitted_owner_resolutions(&evidence, &units, &source, &targets, &attributions).is_empty()
    );
    evidence.objects[1].build_freshness = BuildFreshness::Clean;
    evidence.unscanned_configured_units = 1;
    assert!(
        emitted_owner_resolutions(&evidence, &units, &source, &targets, &attributions).is_empty()
    );
    evidence.unscanned_configured_units = 0;
    assert!(
        emitted_owner_resolutions(
            &evidence,
            &BTreeSet::from(["A.cpp".into(), "B.cpp".into(), "C.cpp".into()]),
            &source,
            &targets,
            &attributions,
        )
        .is_empty()
    );
    targets.push(target("helper", "0x00003020", "0x00003030", 'a'));
    assert!(
        emitted_owner_resolutions(&evidence, &units, &source, &targets, &attributions).is_empty()
    );
}

#[test]
fn matching_instructions_with_unproved_relocations_do_not_prove_emission() {
    let (mut evidence, units, source, targets, attributions) = fixture();
    evidence.objects[0].functions[1].references.push(CompiledReference {
        offset: 4,
        kind: "PpcRel24".into(),
        target: "external".into(),
        target_section: Some(".text".into()),
        target_address: 0,
        addend: 0,
    });
    assert!(
        emitted_owner_resolutions(&evidence, &units, &source, &targets, &attributions).is_empty()
    );
}

#[test]
fn relocation_endpoint_bodies_place_each_copy_and_name_the_excluded_competitor() {
    let (mut evidence, units, _, targets, _) = relocation_fixture();
    let placements = relocation_placements(&evidence, &units, &targets);
    assert_eq!(placements.len(), 2);
    assert_eq!(placements[0].unit, "A.cpp");
    assert_eq!(placements[0].target_address, "0x00001020");
    assert_eq!(placements[0].distinctive_offset, 4);
    assert_eq!(placements[0].excluded_competitors[0].unit, "B.cpp");
    assert_eq!(placements[0].excluded_competitors[0].target_address, "0x00002020");
    assert!(placements.iter().all(|item| item.inventory_complete));

    evidence.unscanned_configured_units = 1;
    let partial = relocation_placements(&evidence, &units, &targets);
    assert_eq!(partial.len(), 2);
    assert!(partial.iter().all(|item| !item.inventory_complete));

    evidence.unscanned_configured_units = 0;
    evidence.target_references[1].references[0].target_address = 0x1000;
    assert!(relocation_placements(&evidence, &units, &targets).is_empty());
}

#[test]
fn an_endpoint_body_repeated_in_another_object_is_not_distinctive() {
    let (mut evidence, units, _, targets, _) = relocation_fixture();
    evidence.objects[1].functions.push(function("extra", "0x00000050", "0x00000070", '1', false));
    assert!(relocation_placements(&evidence, &units, &targets).is_empty());
}

#[test]
fn relocation_placement_survives_stripped_target_names() {
    let (evidence, units, _, mut targets, _) = relocation_fixture();
    let before = relocation_placements(&evidence, &units, &targets);
    for target in &mut targets {
        target.name = format!("fn_{}", target.address.trim_start_matches("0x"));
    }
    assert_eq!(relocation_placements(&evidence, &units, &targets), before);
}

#[test]
fn saved_resolutions_are_rebuilt_from_observations_and_rejected_in_older_schema() {
    let (mut evidence, _, source, targets, attributions) = fixture();
    let mut forged = emitted_owner_resolutions(
        &evidence,
        &BTreeSet::from(["A.cpp".into(), "B.cpp".into()]),
        &source,
        &targets,
        &attributions,
    );
    forged[0].unit = "forged.cpp".into();
    evidence.emitted_owners = forged;
    let mut report = IdentificationReport::empty("NTSC", "PAL");
    report.attributions = attributions;
    report.source_functions = source;
    report.target_functions = targets;
    report.object_evidence = Some(evidence);
    report.units =
        vec![UnitIdentification::absent("A.cpp", 2), UnitIdentification::absent("B.cpp", 2)];
    report.schema = 9;
    assert!(ObservationIndex::load_self_contained(report.clone(), "NTSC", "PAL").is_err());
    report.schema = dtk_migrate::analysis::ownership::IDENTIFICATION_SCHEMA;
    let index = ObservationIndex::load_self_contained(report.clone(), "NTSC", "PAL").unwrap();
    let resolved = &index.report().object_evidence.as_ref().unwrap().emitted_owners;
    assert_eq!(resolved.len(), 2);
    assert_eq!(resolved[0].unit, "A.cpp");
    assert_eq!(resolved[1].unit, "B.cpp");

    let (mut relocated, units, _, targets, _) = relocation_fixture();
    let mut fake = relocation_placements(&relocated, &units, &targets);
    fake[0].unit = "forged.cpp".into();
    relocated.relocation_placements = fake;
    report.object_evidence = Some(relocated);
    let reloaded = ObservationIndex::load_self_contained(report, "NTSC", "PAL").unwrap();
    let placements = &reloaded.report().object_evidence.as_ref().unwrap().relocation_placements;
    assert_eq!(placements.len(), 2);
    assert_eq!(placements[0].unit, "A.cpp");
}
