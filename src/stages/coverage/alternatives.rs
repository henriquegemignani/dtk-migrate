/// Within one kind, the widest claim first.
fn sort_drafts(drafts: &mut [Draft]) {
    drafts.sort_by_key(|draft| (Reverse(draft.end - draft.start), draft.start));
}

/// Every range this unit could claim, strongest evidence first.
pub fn build(
    unit: &CoverageUnit,
    target_blocks: &Blocks,
    source_units: &BTreeMap<String, &CoverageUnit>,
    source_blocks: &Blocks,
    observations: &ObservationIndex,
) -> Vec<Alternative> {
    let mut canonical = unit.clone();
    if let Some(lines) = source_blocks.get(&unit.name) {
        canonical.code_bytes = lines
            .iter()
            .filter_map(|line| parse_range(line))
            .filter(|range| matches!(range.section.as_str(), ".text" | ".init"))
            .map(|range| u64::from(range.end - range.start))
            .sum();
    }
    if let Some(identification) = observations.unit(&unit.name) {
        canonical.source_functions = identification.source_functions;
    }
    let unit = &canonical;
    let eligible: Vec<&CoverageAnchor> = unit
        .anchors
        .iter()
        .filter(|anchor| exact_anchor_eligible(unit, anchor, observations))
        .collect();

    // One anchor at a time: the narrowest claim, and the one most likely to
    // survive when a wider one overlaps something.
    let mut individual: Vec<Draft> = eligible
        .iter()
        .filter_map(|anchor| {
            let start = parse_address(&anchor.target_address)?;
            let end = parse_address(&anchor.target_end)?;
            (!overlaps_other(&unit.name, &anchor.section, start, end, target_blocks)).then(|| {
                alternative(
                    &anchor.section,
                    start,
                    end,
                    vec![value(anchor)],
                    "exact-body",
                    None,
                    vec![],
                )
            })
        })
        .collect();
    sort_drafts(&mut individual);

    // Adjacent anchors merged into one range: more bytes claimed per build.
    let mut ordered: Vec<&&CoverageAnchor> = eligible.iter().collect();
    ordered.sort_by(|a, b| {
        a.section
            .cmp(&b.section)
            .then_with(|| parse_address(&a.target_address).cmp(&parse_address(&b.target_address)))
    });
    let mut runs: Vec<Vec<&CoverageAnchor>> = Vec::new();
    let mut current: Vec<&CoverageAnchor> = Vec::new();
    for anchor in ordered {
        if let Some(last) = current.last()
            && (anchor.section != last.section
                || parse_address(&anchor.target_address) != parse_address(&last.target_end))
        {
            if current.len() > 1 {
                runs.push(std::mem::take(&mut current));
            } else {
                current.clear();
            }
        }
        current.push(anchor);
    }
    if current.len() > 1 {
        runs.push(current);
    }
    let mut combined: Vec<Draft> = runs
        .iter()
        .filter_map(|anchors| {
            let start = parse_address(&anchors[0].target_address)?;
            let end = parse_address(&anchors[anchors.len() - 1].target_end)?;
            (!overlaps_other(&unit.name, &anchors[0].section, start, end, target_blocks)).then(
                || {
                    alternative(
                        &anchors[0].section,
                        start,
                        end,
                        anchors.iter().map(value).collect(),
                        "exact-body",
                        None,
                        vec![],
                    )
                },
            )
        })
        .collect();
    sort_drafts(&mut combined);

    let mut shifted = layout_shift_alternatives(unit, target_blocks, observations);
    sort_drafts(&mut shifted);

    let mut sequences: Vec<Draft> = unit
        .boundary_sequences
        .iter()
        .filter_map(|sequence| sequence_alternative(unit, sequence, target_blocks, observations))
        .collect();
    sort_drafts(&mut sequences);

    let mut adjacent: Vec<Draft> = unit
        .adjacent_owner_transitions
        .iter()
        .filter_map(|transition| {
            adjacent_owner_alternative(
                unit,
                transition,
                target_blocks,
                source_units,
                source_blocks,
                observations,
            )
        })
        .collect();
    sort_drafts(&mut adjacent);

    // A left edge one kind of evidence places and a right edge another
    // places, as one claim. It is tried ahead of the drafts it came from,
    // which stay as fallbacks: if the composition does not hold, they are
    // still what each family alone supports.
    let composed = compositions(
        &unit.name,
        adjacent.iter().chain(&sequences).chain(&shifted).chain(&combined).chain(&individual),
        target_blocks,
        observations,
    );

    // Strongest kind first, and within a kind the biggest range first. A range
    // reached two ways is listed once.
    //
    // `combined` before `individual` is deliberate. Both rest on the same exact
    // bodies, so neither is better supported than the other — and when the
    // evidence is equal the whole run is the better answer to try first. Taking
    // one anchor of it would leave a unit that looks represented, which is the
    // state hardest to get out of. The single-anchor claims stay as fallbacks
    // for when the run turns out not to hold.
    let mut drafts: Vec<Draft> = Vec::new();
    let mut seen: BTreeSet<(String, u32, u32, String)> = BTreeSet::new();
    let complete = complete_sequences(unit, target_blocks, observations);

    for item in composed
        .into_iter()
        .chain(complete)
        .chain(adjacent)
        .chain(sequences)
        .chain(shifted)
        .chain(combined)
        .chain(individual)
    {
        let key = (
            item.section.clone(),
            item.start,
            item.end,
            serde_json::to_string(&item.owner_revisions).unwrap_or_default(),
        );
        if seen.insert(key) {
            drafts.push(item);
        }
    }
    // Last, because only here is it known what every affected unit already
    // holds: each surviving draft becomes one transaction over all of them.
    let setting = Setting {
        unit: &unit.name,
        blocks: target_blocks,
        observations,
        required_extracts: &unit.required_extracts,
        policy: policy_digest(),
    };
    let mut result: Vec<Alternative> =
        drafts.into_iter().filter_map(|draft| finish(draft, &setting)).collect();
    record_competing_edges(&mut result);
    // Evidence quality is global. Generator order must not let a broad but
    // weak sequence outrank a fully attributed exact-body alternative.
    sort_alternatives(&mut result);
    result
}

/// Claims composed from the independently supported edges of other drafts.
///
/// Every draft proposes a left and a right edge. Each distinct address is
/// judged on its own evidence; within one section, a composition is formed
/// only when exactly one left and exactly one right address are supported, and
/// no single draft already proposes both. More than one supported address on a
/// side is a competing hypothesis this rule does not settle. The drafts behind
/// the two edges must agree about every function they both place and keep
/// source order across their union, and the range between may not reach
/// another unit's split. Whether its interior is the unit's is left to the
/// complete ownership assessment every alternative faces, so a composition
/// across an unrelated island is refused there on the island's attribution.
fn compositions<'a>(
    unit: &str,
    drafts: impl Iterator<Item = &'a Draft>,
    target_blocks: &Blocks,
    observations: &ObservationIndex,
) -> Vec<Draft> {
    let mut by_section: BTreeMap<&str, Vec<&Draft>> = BTreeMap::new();
    for draft in drafts.filter(|draft| draft.owner_revisions.is_empty()) {
        by_section.entry(draft.section.as_str()).or_default().push(draft);
    }
    let mut found = Vec::new();
    for (section, drafts) in by_section {
        let mut lefts: BTreeMap<u32, Vec<&Draft>> = BTreeMap::new();
        let mut rights: BTreeMap<u32, Vec<&Draft>> = BTreeMap::new();
        for draft in &drafts {
            lefts.entry(draft.start).or_default().push(draft);
            rights.entry(draft.end).or_default().push(draft);
        }
        let supported = |side: Side, candidates: &BTreeMap<u32, Vec<&Draft>>| -> Vec<u32> {
            candidates
                .keys()
                .copied()
                .filter(|&address| {
                    boundaries::judge(observations, unit, MODULE, section, side, address, vec![])
                        .supported
                })
                .collect()
        };
        let (&[left], &[right]) =
            (&supported(Side::Left, &lefts)[..], &supported(Side::Right, &rights)[..])
        else {
            continue;
        };
        if left >= right
            || drafts.iter().any(|draft| draft.start == left && draft.end == right)
            || overlaps_other(unit, section, left, right, target_blocks)
            || !tiled(observations, section, left, right)
        {
            continue;
        }
        let (from_left, from_right) = (lefts[&left][0], rights[&right][0]);
        let Some(anchors) = compatible_members(from_left, from_right, left, right) else {
            continue;
        };
        let families = |drafts: &[&Draft]| {
            let mut families: Vec<String> = drafts.iter().map(|draft| draft.family()).collect();
            families.dedup();
            families
        };
        found.push(Draft {
            evidence: "composed-boundary".into(),
            support_group: Some(format!(
                "{}@{}|{}@{}",
                from_left.family(),
                format_address(left),
                from_right.family(),
                format_address(right)
            )),
            section: section.to_string(),
            start: left,
            end: right,
            anchors,
            owner_revisions: Vec::new(),
            edge_families: Some((families(&lefts[&left]), families(&rights[&right]))),
        });
    }
    found
}

/// The span of a unit's attributed members in each code section, when the
/// observations confirm it is the unit's complete ordered sequence there.
///
/// This is the route for sequences too small for an ordinary boundary
/// sequence's byte and function minimums. It asks for more than size would:
/// every source function paired in order, nothing unexplained in between, an
/// independent core, and both ends bounded by something other than a split.
/// See [`ObservationIndex::complete_sequence`], which the ownership assessment
/// consults again, so the claim is certified by the same rule that proposed it.
fn complete_sequences(
    unit: &CoverageUnit,
    target_blocks: &Blocks,
    observations: &ObservationIndex,
) -> Vec<Draft> {
    let mut members: BTreeMap<&str, Vec<&crate::analysis::ownership::FunctionAttribution>> =
        BTreeMap::new();
    for item in &observations.report().attributions {
        if item.source.unit == unit.name
            && item.target.module == MODULE
            && item.target.section == item.source.section
            && CODE_SECTIONS.contains(&item.target.section.as_str())
        {
            members.entry(item.target.section.as_str()).or_default().push(item);
        }
    }
    let mut found = Vec::new();
    for (section, mut members) in members {
        members.sort_by_key(|item| parse_address(&item.target.address));
        let (Some(start), Some(end)) = (
            members.first().and_then(|item| parse_address(&item.target.address)),
            members.last().and_then(|item| parse_address(&item.target.end)),
        ) else {
            continue;
        };
        let Some(sequence) =
            observations.complete_sequence(&unit.name, MODULE, section, start, end)
        else {
            continue;
        };
        if overlaps_other(&unit.name, section, start, end, target_blocks) {
            continue;
        }
        let anchors = members
            .iter()
            .map(|item| {
                serde_json::json!({
                    "section": section,
                    "source_name": item.source.name,
                    "source_address": item.source.address,
                    "target_address": item.target.address,
                    "target_end": item.target.end,
                    "attribution_id": item.id,
                    "independent": item.independent,
                })
            })
            .collect();
        found.push(alternative(
            section,
            start,
            end,
            anchors,
            "complete-sequence",
            Some(serde_json::to_string(&(&sequence.left, &sequence.right)).unwrap_or_default()),
            vec![],
        ));
    }
    found
}

/// Code sections a sequence may be recovered in.
const CODE_SECTIONS: [&str; 2] = [".init", ".text"];

/// Whether target functions tile `start..end` with nothing but alignment
/// padding between them, and none reaching past either end.
fn tiled(observations: &ObservationIndex, section: &str, start: u32, end: u32) -> bool {
    let mut cursor = start;
    for function in observations.section_functions(MODULE, section) {
        let (Some(left), Some(right)) =
            (parse_address(&function.address), parse_address(&function.end))
        else {
            return false;
        };
        if right <= start || left >= end {
            continue;
        }
        if left < start || right > end || left - cursor > MAX_COMPOSED_PADDING_GAP {
            return false;
        }
        cursor = right;
    }
    cursor > start && end - cursor <= MAX_COMPOSED_PADDING_GAP
}

/// The union of two drafts' member records, when they describe one ordered
/// sequence: no target function placed from two different source functions,
/// source order kept across the union, and every member inside the claim.
fn compatible_members(
    left: &Draft,
    right: &Draft,
    start: u32,
    end: u32,
) -> Option<Vec<serde_json::Value>> {
    let mut members: BTreeMap<u32, (u32, serde_json::Value)> = BTreeMap::new();
    for anchor in left.anchors.iter().chain(&right.anchors) {
        let target = parse_address(anchor.get("target_address")?.as_str()?)?;
        let source = parse_address(anchor.get("source_address")?.as_str()?)?;
        let target_end = parse_address(anchor.get("target_end")?.as_str()?)?;
        if target < start || target_end > end {
            return None;
        }
        match members.get(&target) {
            Some((known, _)) if *known != source => return None,
            Some(_) => {}
            None => {
                members.insert(target, (source, anchor.clone()));
            }
        }
    }
    let sources: Vec<u32> = members.values().map(|(source, _)| *source).collect();
    (!members.is_empty() && sources.windows(2).all(|pair| pair[0] < pair[1]))
        .then(|| members.into_values().map(|(_, anchor)| anchor).collect())
}

/// Ranges claimed by a group of functions that differ only where a member
/// offset moved.
fn layout_shift_alternatives(
    unit: &CoverageUnit,
    target_blocks: &Blocks,
    observations: &ObservationIndex,
) -> Vec<Draft> {
    let mut groups: IndexMap<String, Vec<&LayoutShiftAnchor>> = IndexMap::new();
    for anchor in unit
        .layout_shift_anchors
        .iter()
        .filter(|anchor| layout_anchor_eligible(unit, anchor, observations))
    {
        groups.entry(anchor.support_group.clone()).or_default().push(anchor);
    }

    let mut found = Vec::new();
    for (group, mut anchors) in groups {
        anchors.sort_by_key(|anchor| parse_address(&anchor.target_address));
        let sections: BTreeSet<&str> = anchors.iter().map(|a| a.section.as_str()).collect();
        let deltas: BTreeSet<&[i32]> = anchors.iter().map(|a| a.offset_deltas.as_slice()).collect();
        let breakpoints: BTreeSet<Option<i32>> =
            anchors.iter().map(|a| a.inferred_breakpoint).collect();
        let source_addresses: Vec<Option<u32>> =
            anchors.iter().map(|a| parse_address(&a.source_address)).collect();
        let ranges: Vec<(Option<u32>, Option<u32>)> = anchors
            .iter()
            .map(|a| (parse_address(&a.target_address), parse_address(&a.target_end)))
            .collect();

        // Every member must agree on the same group, the same transformation,
        // and the same totals; a group whose members disagree about itself is
        // not evidence of anything.
        let total_size: u32 = anchors.iter().map(|a| a.size).sum();
        let total_changed: u32 = anchors.iter().map(|a| a.changed_this_accesses).sum();
        if anchors.len() < 2
            || anchors.len() < MIN_LAYOUT_SHIFT_FUNCTIONS as usize
            || total_size < MIN_LAYOUT_SHIFT_BYTES
            || total_changed < MIN_LAYOUT_SHIFT_CHANGED_ACCESSES
            || sections.len() != 1
            || deltas.len() != 1
            || breakpoints.len() != 1
            || source_addresses.iter().any(Option::is_none)
            || !source_addresses.windows(2).all(|pair| pair[0] < pair[1])
            || ranges.iter().any(|(a, b)| a.is_none() || b.is_none())
            || ranges.windows(2).any(|pair| pair[1].0 < pair[0].1)
        {
            continue;
        }
        let start = ranges[0].0.unwrap();
        let end = ranges.iter().filter_map(|(_, end)| *end).max().unwrap_or(start);
        // A group spanning more than twice the unit's own code has drifted into
        // something else's territory.
        if u64::from(end - start) > 2 * unit.code_bytes {
            continue;
        }
        let section = anchors[0].section.clone();
        if overlaps_other(&unit.name, &section, start, end, target_blocks) {
            continue;
        }
        found.push(alternative(
            &section,
            start,
            end,
            anchors.iter().map(value).collect(),
            "this-layout-shift",
            Some(group),
            vec![],
        ));
    }
    found
}

/// A range bounded by two units whose position is already known.
fn sequence_alternative(
    unit: &CoverageUnit,
    sequence: &BoundarySequence,
    target_blocks: &Blocks,
    observations: &ObservationIndex,
) -> Option<Draft> {
    let start = parse_address(&sequence.target_start)?;
    let end = parse_address(&sequence.target_end)?;
    if sequence.section != ".text"
        || end <= start
        || sequence.target_bytes != end - start
        || overlaps_other(&unit.name, &sequence.section, start, end, target_blocks)
    {
        return None;
    }

    match sequence.acceptance_method.as_str() {
        "ownership-transition-boundary" => {
            ownership_transition(unit, sequence, start, end, observations)
        }
        "layout-corroborated-boundary" => {
            layout_corroborated(unit, sequence, start, end, observations)
        }
        "vtable-corroborated-boundary" => {
            vtable_corroborated(unit, sequence, start, end, observations)
        }
        "matched-sequence" => matched_sequence(unit, sequence, start, end, observations),
        _ => None,
    }
}

/// A stale neighbouring split made the bounded gap too wide; the candidate's
/// own aligned run trims it, and the two edges must transfer cleanly.
fn ownership_transition(
    unit: &CoverageUnit,
    sequence: &BoundarySequence,
    start: u32,
    end: u32,
    observations: &ObservationIndex,
) -> Option<Draft> {
    let functions = &sequence.functions;
    let support = sequence.ownership_transition_support.as_ref()?;
    let (ranges, strong) = sequence_details(functions)?;
    let original_start = parse_address(&support.original_target_start)?;
    let original_end = parse_address(&support.original_target_end)?;
    let aligned_start = parse_address(&support.aligned_target_start)?;
    let aligned_end = parse_address(&support.aligned_target_end)?;
    let size_delta = relative_size_delta(unit.code_bytes as u32, end - start);
    let source_functions =
        observations.source_function_count(&unit.name, "main", &sequence.section);
    let target_functions =
        observations.target_function_count("main", &sequence.section, start, end);

    if !sequence_is_observed(&unit.name, &sequence.section, functions, observations)
        || functions.len() < MIN_OWNERSHIP_TRANSITION_FUNCTIONS as usize
        || source_functions as usize != functions.len()
        || target_functions as usize != functions.len()
        || alignment_margin(sequence.best_alignment_score, sequence.second_alignment_score)
            < MIN_SEQUENCE_ALIGNMENT_MARGIN
        || strong < MIN_OWNERSHIP_TRANSITION_STRONG_FUNCTIONS
        // The run must tile the whole claimed range, end to end.
        || ranges.windows(2).any(|pair| pair[0].1 != pair[1].0)
        || ranges.first()?.0 != start
        || ranges.last()?.1 != end
        || aligned_start != start
        || aligned_end != end
        // The original range must strictly contain the trimmed one.
        || original_start > start
        || original_end < end
        || original_start >= original_end
        || (original_start == start && original_end == end)
        || size_delta > MAX_OWNERSHIP_TRANSITION_SIZE_DELTA
        || !valid_transition_edge(&support.left, &sequence.previous_unit, original_start, start)
        || !valid_transition_edge(&support.right, &sequence.next_unit, end, original_end)
    {
        return None;
    }
    Some(alternative(
        &sequence.section,
        start,
        end,
        functions.iter().map(|f| anchor_value(f, &sequence.section)).collect(),
        "ownership-transition-boundary",
        Some(format!(
            "{}|{}|{}|{}",
            sequence.previous_unit,
            sequence.next_unit,
            support.original_target_start,
            support.original_target_end
        )),
        vec![],
    ))
}

/// One side of an ownership transfer: the part of the old range that stays with
/// its original owner.
fn valid_transition_edge(
    edge: &crate::analysis::coverage::OwnershipTransitionEdge,
    unit: &str,
    start: u32,
    end: u32,
) -> bool {
    let mut ranges = Vec::with_capacity(edge.functions.len());
    let mut source_addresses = Vec::with_capacity(edge.functions.len());
    for function in &edge.functions {
        let (Some(left), Some(right), Some(source)) = (
            parse_address(&function.target_address),
            parse_address(&function.target_end),
            parse_address(&function.source_address),
        ) else {
            return false;
        };
        if right <= left || right - left != function.size {
            return false;
        }
        ranges.push((left, right));
        source_addresses.push(source);
    }
    let strong = strong_count(edge.functions.iter().map(|f| f.tier.as_str()));
    if edge.unit != unit
        || parse_address(&edge.start) != Some(start)
        || parse_address(&edge.end) != Some(end)
        || edge.bytes != end - start
        || edge.functions.iter().any(|f| !MATCH_TIERS.contains(&f.tier.as_str()))
        || !source_addresses.windows(2).all(|pair| pair[0] < pair[1])
        || ranges.windows(2).any(|pair| pair[0].1 != pair[1].0)
    {
        return false;
    }
    // An empty edge is allowed, and then it must really be empty.
    if start == end {
        return edge.functions.is_empty() && strong == 0;
    }
    !edge.functions.is_empty()
        && ranges[0].0 == start
        && ranges[ranges.len() - 1].1 == end
        && strong >= MIN_OWNERSHIP_TRANSITION_EDGE_STRONG_FUNCTIONS
}

/// Ordinary matching was inconclusive, but enough layout-shift functions agree
/// to corroborate the whole neighbour-bounded gap.
fn layout_corroborated(
    unit: &CoverageUnit,
    sequence: &BoundarySequence,
    start: u32,
    end: u32,
    observations: &ObservationIndex,
) -> Option<Draft> {
    let group = sequence.layout_support_group.as_ref()?;
    let mut anchors: Vec<&LayoutShiftAnchor> = unit
        .layout_shift_anchors
        .iter()
        .filter(|anchor| {
            layout_anchor_eligible(unit, anchor, observations) && &anchor.support_group == group
        })
        .collect();
    anchors.sort_by_key(|anchor| parse_address(&anchor.source_address));
    if anchors.is_empty() {
        return None;
    }

    let total_size: u32 = anchors.iter().map(|a| a.size).sum();
    let total_changed: u32 = anchors.iter().map(|a| a.changed_this_accesses).sum();
    let deltas: BTreeSet<&[i32]> = anchors.iter().map(|a| a.offset_deltas.as_slice()).collect();
    let breakpoints: BTreeSet<Option<i32>> =
        anchors.iter().map(|a| a.inferred_breakpoint).collect();
    let source_addresses: Vec<Option<u32>> =
        anchors.iter().map(|a| parse_address(&a.source_address)).collect();
    let ranges: Vec<(Option<u32>, Option<u32>)> = anchors
        .iter()
        .map(|a| (parse_address(&a.target_address), parse_address(&a.target_end)))
        .collect();
    let size_delta = relative_size_delta(unit.code_bytes as u32, end - start);
    let delta_length = deltas.iter().next().map(|d| d.len()).unwrap_or(0);
    let source_functions =
        observations.source_function_count(&unit.name, "main", &sequence.section);
    let target_functions =
        observations.target_function_count("main", &sequence.section, start, end);

    if deltas.len() != 1
        // One constant offset shift, or two separated by a single breakpoint.
        || !(1..=2).contains(&delta_length)
        || breakpoints.len() != 1
        || anchors.len() < MIN_LAYOUT_BOUNDARY_FUNCTIONS as usize
        || total_size < MIN_LAYOUT_BOUNDARY_BYTES
        || total_changed < MIN_LAYOUT_BOUNDARY_CHANGED_ACCESSES
        || size_delta > MAX_LAYOUT_BOUNDARY_SIZE_DELTA
        || (i64::from(source_functions) - i64::from(target_functions)).abs()
            > i64::from(MAX_LAYOUT_BOUNDARY_FUNCTION_DELTA)
        || source_addresses.iter().any(Option::is_none)
        || !source_addresses.windows(2).all(|pair| pair[0] < pair[1])
        || ranges.iter().any(|(a, b)| a.is_none() || b.is_none())
        || ranges.windows(2).any(|pair| pair[1].0 < pair[0].1)
        || ranges.iter().any(|(a, b)| a.unwrap() < start || b.unwrap() > end)
    {
        return None;
    }
    Some(alternative(
        &sequence.section,
        start,
        end,
        anchors.iter().map(value).collect(),
        "layout-corroborated-boundary",
        Some(format!("{}|{}|{group}", sequence.previous_unit, sequence.next_unit)),
        vec![],
    ))
}

/// A polymorphic class whose compiler output moved one body into a local
/// helper, corroborated by a uniquely paired vtable.
fn vtable_corroborated(
    unit: &CoverageUnit,
    sequence: &BoundarySequence,
    start: u32,
    end: u32,
    observations: &ObservationIndex,
) -> Option<Draft> {
    let functions = &sequence.functions;
    let support = sequence.vtable_support.as_ref()?;
    let helpers = &sequence.gap_helpers;

    let mut ranges = Vec::with_capacity(functions.len());
    let mut source_addresses = Vec::with_capacity(functions.len());
    for function in functions {
        let (Some(left), Some(right), Some(source)) = (
            parse_address(&function.target_address),
            parse_address(&function.target_end),
            parse_address(&function.source_address),
        ) else {
            return None;
        };
        if right <= left || right - left != function.size {
            return None;
        }
        ranges.push((left, right));
        source_addresses.push(source);
    }
    let mut helper_ranges = Vec::with_capacity(helpers.len());
    for helper in helpers {
        let (Some(left), Some(right)) =
            (parse_address(&helper.target_address), parse_address(&helper.target_end))
        else {
            return None;
        };
        helper_ranges.push((left, right));
    }

    let target_addresses: BTreeSet<u32> = ranges.iter().map(|(left, _)| *left).collect();
    let helper_addresses: BTreeSet<u32> = helper_ranges.iter().map(|(left, _)| *left).collect();
    let allowed_callers: BTreeSet<u32> =
        target_addresses.union(&helper_addresses).copied().collect();
    let function_pairs: BTreeSet<(&str, &str)> =
        functions.iter().map(|f| (f.source_address.as_str(), f.target_address.as_str())).collect();
    let slot_pairs: BTreeSet<(&str, &str)> = support
        .unit_slots
        .iter()
        .map(|slot| (slot.source_address.as_str(), slot.target_address.as_str()))
        .collect();
    let slot_offsets: BTreeSet<u32> = support.unit_slots.iter().map(|s| s.slot_offset).collect();

    let aligned_bytes: u32 = functions.iter().map(|f| f.size).sum();
    let size_delta = relative_size_delta(unit.code_bytes as u32, end - start);
    let source_functions =
        observations.source_function_count(&unit.name, "main", &sequence.section);
    let target_functions =
        observations.target_function_count("main", &sequence.section, start, end);

    let helper_ok = |index: usize| -> bool {
        let helper = &helpers[index];
        let (left, right) = helper_ranges[index];
        let callers: Vec<Option<u32>> = helper.callers.iter().map(|c| parse_address(c)).collect();
        right > left
            && right - left == helper.size
            && left >= start
            && right <= end
            && !helper.callers.is_empty()
            && callers.iter().all(|c| c.is_some_and(|c| allowed_callers.contains(&c)))
            // The helper must be called from inside the gap, not only by
            // another helper.
            && callers.iter().any(|c| c.is_some_and(|c| target_addresses.contains(&c)))
    };

    if !sequence_is_observed(&unit.name, &sequence.section, functions, observations)
        || functions.len() < MIN_VTABLE_BOUNDARY_FUNCTIONS as usize
        || source_functions == 0
        || (functions.len() as f32 / source_functions as f32) < MIN_VTABLE_BOUNDARY_MATCH_RATIO
        || (aligned_bytes as f32 / (end - start) as f32)
            < MIN_VTABLE_BOUNDARY_TARGET_COVERAGE
        // At most one source function may be unaccounted for.
        || !(0..=1).contains(&(i64::from(source_functions) - functions.len() as i64))
        || (i64::from(source_functions) - i64::from(target_functions)).abs()
            > i64::from(MAX_VTABLE_BOUNDARY_FUNCTION_DELTA)
        || size_delta > MAX_VTABLE_BOUNDARY_SIZE_DELTA
        || functions.iter().any(|f| !f.primary)
        || !source_addresses.windows(2).all(|pair| pair[0] < pair[1])
        || ranges.windows(2).any(|pair| pair[1].0 < pair[0].1)
        || ranges.iter().any(|(left, right)| *left < start || *right > end)
        || support.source_address.is_empty()
        || support.target_address.is_empty()
        || support.matched_slots < MIN_VTABLE_BOUNDARY_MATCHED_SLOTS
        || support.agreeing_slots != support.matched_slots
        || support.unit_slots.len() < MIN_VTABLE_BOUNDARY_UNIT_SLOTS as usize
        || support.unit_slots.len() > support.agreeing_slots as usize
        || slot_offsets.len() != support.unit_slots.len()
        || slot_offsets.iter().any(|offset| offset % 4 != 0 || *offset >= support.source_size)
        // Every vtable slot must name a function this sequence also matched.
        || !slot_pairs.is_subset(&function_pairs)
        || support.source_size == 0
        || support.target_size == 0
        || (i64::from(support.source_size) - i64::from(support.target_size)).abs()
            > i64::from(MAX_VTABLE_SIZE_PADDING)
        || !(1..=MAX_VTABLE_BOUNDARY_GAP_HELPERS as usize).contains(&helpers.len())
        || helpers.len() as i64 != i64::from(target_functions) - functions.len() as i64
        || !(0..helpers.len()).all(helper_ok)
        || helper_ranges
            .iter()
            .any(|(left, right)| ranges.iter().any(|(a, b)| left < b && a < right))
        || helper_ranges.iter().enumerate().any(|(index, (left, right))| {
            helper_ranges[index + 1..].iter().any(|(a, b)| left < b && a < right)
        })
    {
        return None;
    }
    Some(alternative(
        &sequence.section,
        start,
        end,
        functions.iter().map(|f| anchor_value(f, &sequence.section)).collect(),
        "vtable-corroborated-boundary",
        Some(format!(
            "{}|{}|{}|{}",
            sequence.previous_unit,
            sequence.next_unit,
            support.source_address,
            support.target_address
        )),
        vec![],
    ))
}

/// The plain case: a decisive monotone alignment across the whole gap.
fn matched_sequence(
    unit: &CoverageUnit,
    sequence: &BoundarySequence,
    start: u32,
    end: u32,
    observations: &ObservationIndex,
) -> Option<Draft> {
    let functions = &sequence.functions;
    let (ranges, strong) = sequence_details(functions)?;
    let aligned_bytes: u32 = functions.iter().map(|f| f.size).sum();
    let source_functions =
        observations.source_function_count(&unit.name, "main", &sequence.section);
    let target_functions =
        observations.target_function_count("main", &sequence.section, start, end);
    let direct_anchors =
        observations.independent_members(&unit.name, "main", &sequence.section, start, end);
    let match_ratio =
        if source_functions == 0 { 0.0 } else { functions.len() as f32 / source_functions as f32 };
    let target_coverage =
        if end == start { 0.0 } else { aligned_bytes as f32 / (end - start) as f32 };
    let alignment_margin = if sequence.best_alignment_score <= 0.0 {
        0.0
    } else {
        (sequence.best_alignment_score - sequence.second_alignment_score).max(0.0)
            / sequence.best_alignment_score
    };
    if !sequence_is_observed(&unit.name, &sequence.section, functions, observations)
        || functions.len() < MIN_SEQUENCE_FUNCTIONS as usize
        || aligned_bytes < MIN_SEQUENCE_MATCHED_BYTES
        || match_ratio < MIN_SEQUENCE_MATCH_RATIO
        || target_coverage < MIN_SEQUENCE_TARGET_COVERAGE
        || strong < MIN_SEQUENCE_STRONG_FUNCTIONS
        || direct_anchors < MIN_SEQUENCE_DIRECT_ANCHORS
        || alignment_margin < MIN_SEQUENCE_ALIGNMENT_MARGIN
        || target_functions < functions.len() as u32
        || ranges.windows(2).any(|pair| pair[1].0 < pair[0].1)
        || ranges.iter().any(|(left, right)| *left < start || *right > end)
    {
        return None;
    }
    Some(alternative(
        &sequence.section,
        start,
        end,
        functions.iter().map(|f| anchor_value(f, &sequence.section)).collect(),
        "boundary-sequence",
        Some(format!("{}|{}", sequence.previous_unit, sequence.next_unit)),
        vec![],
    ))
}

/// The candidate's run occupies a prefix or suffix of an adjacent unit's
/// declared range, so that unit shrinks and the candidate takes what it gives
/// up — one transaction, both or neither.
fn adjacent_owner_alternative(
    unit: &CoverageUnit,
    transition: &AdjacentOwnerTransition,
    target_blocks: &Blocks,
    source_units: &BTreeMap<String, &CoverageUnit>,
    source_blocks: &Blocks,
    observations: &ObservationIndex,
) -> Option<Draft> {
    let section = transition.section.as_str();
    let side = transition.side.as_str();
    let start = parse_address(&transition.target_start)?;
    let end = parse_address(&transition.target_end)?;
    let owner = &transition.owner;
    let original_start = parse_address(&owner.original_start)?;
    let original_end = parse_address(&owner.original_end)?;
    let revised_start = parse_address(&owner.revised_start)?;
    let revised_end = parse_address(&owner.revised_end)?;

    source_units.get(owner.unit.as_str())?;
    let (candidate_ranges, candidate_strong) = sequence_details(&transition.functions)?;
    let (owner_ranges, owner_strong) = sequence_details(&owner.functions)?;
    let current_owner_range = single_section_range(target_blocks, &owner.unit, section);
    let previous_range = single_section_range(target_blocks, &transition.previous_unit, section);
    let next_range = single_section_range(target_blocks, &transition.next_unit, section);
    let source_previous = single_section_range(source_blocks, &transition.previous_unit, section)?;
    let source_candidate = single_section_range(source_blocks, &unit.name, section)?;
    let source_next = single_section_range(source_blocks, &transition.next_unit, section)?;

    // The three units must be contiguous in the source version, in that order,
    // and the candidate's source range must be exactly its code.
    if section != ".text"
        || !matches!(side, "next-prefix" | "previous-suffix")
        || end <= start
        || current_owner_range != Some((original_start, original_end))
        || owner.unit == unit.name
        || !source_units.contains_key(transition.previous_unit.as_str())
        || !source_units.contains_key(transition.next_unit.as_str())
        || source_previous.1 != source_candidate.0
        || source_candidate.1 != source_next.0
    {
        return None;
    }

    let helpers = &owner.gap_helpers;
    let candidate_bytes = end - start;
    let owner_bytes = revised_end.checked_sub(revised_start)?;
    let candidate_delta =
        relative_size_delta(source_candidate.1 - source_candidate.0, candidate_bytes);
    let owner_source_bytes = if owner.unit == transition.next_unit {
        source_next.1 - source_next.0
    } else {
        source_previous.1 - source_previous.0
    };
    let owner_delta = relative_size_delta(owner_source_bytes, owner_bytes);
    let direct_anchors = direct_anchor_count(unit, section, start, end, &owner.unit, observations);
    let candidate_source_functions =
        observations.source_function_count(&unit.name, "main", section);
    let candidate_target_functions =
        observations.target_function_count("main", section, start, end);
    let owner_source_functions = observations.source_function_count(&owner.unit, "main", section);
    let owner_target_functions =
        observations.target_function_count("main", section, revised_start, revised_end);
    let target_addresses: BTreeSet<u32> = owner_ranges.iter().map(|(left, _)| *left).collect();
    let helper_addresses: BTreeSet<u32> =
        helpers.iter().filter_map(|h| parse_address(&h.target_address)).collect();
    let allowed_callers: BTreeSet<u32> =
        target_addresses.union(&helper_addresses).copied().collect();

    if !sequence_is_observed(&unit.name, section, &transition.functions, observations)
        || !sequence_is_observed(&owner.unit, section, &owner.functions, observations)
        || transition.functions.len() < MIN_ADJACENT_OWNER_TRANSITION_FUNCTIONS as usize
        || candidate_source_functions as usize != transition.functions.len()
        || candidate_target_functions as usize != transition.functions.len()
        || candidate_strong < MIN_ADJACENT_OWNER_TRANSITION_STRONG_FUNCTIONS
        || direct_anchors < MIN_ADJACENT_OWNER_TRANSITION_DIRECT_ANCHORS
        || alignment_margin(transition.best_alignment_score, transition.second_alignment_score)
            < MIN_SEQUENCE_ALIGNMENT_MARGIN
        || [start, end, revised_start, revised_end].iter().any(|value| value % 4 != 0)
        || candidate_delta > MAX_ADJACENT_OWNER_SIZE_DELTA
        || !partition_covers(start, end, &candidate_ranges, &[])
        || owner_source_functions as usize != owner.functions.len()
        || owner.functions.len() < MIN_ADJACENT_OWNER_SUPPORT_FUNCTIONS as usize
        || owner_strong < MIN_ADJACENT_OWNER_SUPPORT_STRONG_FUNCTIONS
        || owner_target_functions as usize != owner.functions.len() + helpers.len()
        || owner_delta > MAX_ADJACENT_OWNER_SIZE_DELTA
        || helpers.len() > MAX_ADJACENT_OWNER_GAP_HELPERS as usize
        || !partition_covers(revised_start, revised_end, &owner_ranges, helpers)
        || helpers.iter().any(|helper| {
            let callers: Vec<Option<u32>> =
                helper.callers.iter().map(|c| parse_address(c)).collect();
            helper.callers.is_empty()
                || !callers.iter().all(|c| c.is_some_and(|c| allowed_callers.contains(&c)))
                || !callers.iter().any(|c| c.is_some_and(|c| target_addresses.contains(&c)))
        })
    {
        return None;
    }

    // The candidate must sit exactly where the retained owner gives way, with
    // the far side already pinned by a unit that is not moving.
    let valid_boundary = if side == "next-prefix" {
        owner.unit == transition.next_unit
            && previous_range.is_some_and(|range| range.1 == start)
            && next_range == current_owner_range
            && original_start < end
            && end < original_end
            && revised_start == end
            && revised_end == original_end
    } else {
        owner.unit == transition.previous_unit
            && next_range.is_some_and(|range| range.0 == end)
            && previous_range == current_owner_range
            && original_start < start
            && start < original_end
            && revised_start == original_start
            && revised_end == start
    };
    let relinquished = if side == "next-prefix" {
        (original_start, revised_start)
    } else {
        (revised_end, original_end)
    };
    let overlaps: Vec<(&str, u32, u32)> = target_blocks
        .iter()
        .flat_map(|(name, lines)| lines.iter().map(move |line| (name, line)))
        .filter_map(|(name, line)| {
            let range = parse_range(line)?;
            (range.section == section && start < range.end && range.start < end).then_some((
                name.as_str(),
                range.start,
                range.end,
            ))
        })
        .collect();

    if !valid_boundary
        || relinquished.0 >= relinquished.1
        || overlaps.iter().any(|(name, _, _)| *name != owner.unit)
        || !overlaps.iter().any(|(name, other_start, other_end)| {
            *name == owner.unit
                && start.max(*other_start) == relinquished.0
                && end.min(*other_end) == relinquished.1
        })
    {
        return None;
    }

    Some(alternative(
        section,
        start,
        end,
        transition.functions.iter().map(|f| anchor_value(f, section)).collect(),
        "adjacent-owner-transition-boundary",
        Some(format!(
            "{}|{}|{side}|{}|{}",
            transition.previous_unit,
            transition.next_unit,
            owner.original_start,
            owner.original_end
        )),
        vec![OwnerRevision {
            unit: owner.unit.clone(),
            section: section.to_string(),
            original_start: owner.original_start.clone(),
            original_end: owner.original_end.clone(),
            revised_start: owner.revised_start.clone(),
            revised_end: owner.revised_end.clone(),
        }],
    ))
}

/// Why a unit produced no alternative, in one word.
///
/// Every missing unit gets one, so the report accounts for all of them rather
/// than only the ones something could be done about.
pub fn disposition(unit: &CoverageUnit, alternatives: &[Alternative], represented: bool) -> String {
    if !alternatives.is_empty() {
        return "eligible".into();
    }
    // Said before the evidence reasons below, which would otherwise describe a
    // unit that is simply finished as though something had gone wrong with it.
    if represented {
        return "represented-and-unextendable".into();
    }
    if unit.code_bytes == 0 {
        return "zero-code".into();
    }
    if unit.code_bytes < 256 {
        return "tiny-code".into();
    }
    if unit.ambiguous_exact_bodies > 0 {
        return "ambiguous-shared-evidence".into();
    }
    let reasons: BTreeSet<&str> = unit
        .anchors
        .iter()
        .flat_map(|a| a.reasons.iter())
        .chain(unit.layout_shift_anchors.iter().flat_map(|a| a.reasons.iter()))
        .map(String::as_str)
        .collect();
    if reasons.contains("target range is owned by another explicit unit") {
        return "overlap".into();
    }
    if reasons.contains("function range is not split-aligned") {
        return "alignment".into();
    }
    if unit.layout_shift_candidates > 0 {
        return "layout-shift-insufficient-support".into();
    }
    if !unit.boundary_sequences.is_empty() {
        return "boundary-sequence-insufficient-support".into();
    }
    "no-qualifying-anchor".into()
}

