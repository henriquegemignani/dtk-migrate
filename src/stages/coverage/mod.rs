/// The evidence schema this stage understands.
pub const EVIDENCE_SCHEMA: u32 = 11;
pub const POLICY_VERSION: u32 = crate::analysis::policy::POLICY_VERSION;

const VALIDATION: &str = "atomic-ownership-transactions-with-exact-preconditions-and-canonical-attributed-ownership-and-unique-exact-or-corroborated-layout-or-boundary-sequence-or-bounded-layout-or-vtable-helper-or-ownership-transition-or-adjacent-owner-transition-or-composed-independent-edges-or-decisive-joint-unit-runs-required-extracts-and-extracted-link-inputs-and-retail-bytes";

const CODE_SECTIONS: [&str; 2] = [".text", ".init"];
const OTHER_LINES: &str = "<unparsed>";

fn body_by_section(lines: &[String]) -> BTreeMap<String, Vec<String>> {
    let mut sections = BTreeMap::new();
    for line in lines {
        let section = parse_range(line).map_or_else(|| OTHER_LINES.to_string(), |r| r.section);
        sections.entry(section).or_insert_with(Vec::new).push(line.clone());
    }
    sections
}

fn changes_data(before: Option<&[String]>, after: &[String]) -> bool {
    let before = body_by_section(before.unwrap_or_default());
    let after = body_by_section(after);
    before.keys().chain(after.keys()).any(|section| {
        !CODE_SECTIONS.contains(&section.as_str()) && before.get(section) != after.get(section)
    })
}

pub(crate) fn changed_sections(transaction: &OwnershipTransaction) -> BTreeSet<String> {
    let mut sections = BTreeSet::new();
    for member in &transaction.members {
        let before = body_by_section(member.before.as_deref().unwrap_or_default());
        let after = body_by_section(&member.after);
        for section in before.keys().chain(after.keys()) {
            if before.get(section) != after.get(section) {
                sections.insert(section.clone());
            }
        }
    }
    sections
}

fn read_dependency_scopes(transaction: &OwnershipTransaction) -> BTreeSet<MutationScope> {
    let sections = changed_sections(transaction);
    let code = sections.iter().any(|section| CODE_SECTIONS.contains(&section.as_str()));
    let data = sections.iter().any(|section| !CODE_SECTIONS.contains(&section.as_str()));
    let mut scopes = BTreeSet::new();
    for read in &transaction.reads {
        if code {
            scopes.insert(MutationScope::CodeDependency(read.unit.clone()));
        }
        if data {
            scopes.insert(MutationScope::DataDependency(read.unit.clone()));
        }
    }
    scopes
}

fn validate_read_dependencies(
    transaction: &OwnershipTransaction,
    blocks: &IndexMap<String, Vec<String>>,
) -> Result<()> {
    let sections = changed_sections(transaction);
    for read in &transaction.reads {
        let expected = body_by_section(read.body.as_deref().unwrap_or_default());
        let current =
            body_by_section(blocks.get(&read.unit).map(Vec::as_slice).unwrap_or_default());
        for section in &sections {
            if expected.get(section) != current.get(section) {
                bail!(ValidationError(format!(
                    "Coverage dependency {} changed in {section} after transaction {}",
                    read.unit, transaction.id
                )));
            }
        }
    }
    Ok(())
}

fn transaction_scopes(transaction: &OwnershipTransaction) -> BTreeSet<MutationScope> {
    let mut scopes = BTreeSet::new();
    for member in &transaction.members {
        let before = body_by_section(member.before.as_deref().unwrap_or_default());
        let after = body_by_section(&member.after);
        if CODE_SECTIONS.iter().any(|section| before.get(*section) != after.get(*section)) {
            scopes.insert(MutationScope::Unit(member.unit.clone()));
        }
        if changes_data(member.before.as_deref(), &member.after) {
            scopes.insert(MutationScope::UnitData(member.unit.clone()));
        }
    }
    scopes
}

/// Reconstructs the last exact coverage state for historical transaction
/// replay, but only after confirming the final project retains every section
/// coverage certified. Later data additions in untouched sections are checked
/// by their own stage; they must not invalidate an otherwise unchanged code
/// boundary certificate.
fn coverage_history_projection(
    final_blocks: &IndexMap<String, Vec<String>>,
    transactions: &[&OwnershipTransaction],
) -> Result<IndexMap<String, Vec<String>>> {
    let mut protected: BTreeMap<String, BTreeSet<String>> = BTreeMap::new();
    let mut last_after: BTreeMap<String, Vec<String>> = BTreeMap::new();
    for transaction in transactions {
        for member in &transaction.members {
            let before = body_by_section(member.before.as_deref().unwrap_or_default());
            let after = body_by_section(&member.after);
            let sections = protected.entry(member.unit.clone()).or_default();
            sections.extend(CODE_SECTIONS.iter().map(|name| (*name).to_string()));
            sections.insert(OTHER_LINES.to_string());
            for section in before.keys().chain(after.keys()) {
                if before.get(section) != after.get(section) {
                    sections.insert(section.clone());
                }
            }
            last_after.insert(member.unit.clone(), member.after.clone());
        }
    }

    let mut projected = final_blocks.clone();
    for (unit, after) in last_after {
        let final_sections =
            body_by_section(final_blocks.get(&unit).map(Vec::as_slice).unwrap_or_default());
        let after_sections = body_by_section(&after);
        for section in &protected[&unit] {
            if final_sections.get(section) != after_sections.get(section) {
                bail!(ValidationError(format!(
                    "Coverage ownership for {unit} changed in {section} after its certificate"
                )));
            }
        }
        projected.insert(unit, after);
    }
    Ok(projected)
}

fn validate_evidence(
    mut evidence: CoverageReport,
    expected_units: &BTreeSet<String>,
    source: &str,
    target: &str,
) -> Result<(CoverageReport, ObservationIndex)> {
    if evidence.schema != EVIDENCE_SCHEMA
        || evidence.policy != crate::analysis::policy::current_policy()
    {
        bail!(
            "Coverage evidence is schema {} policy {}, and this stage requires schema {EVIDENCE_SCHEMA} and policy {POLICY_VERSION} with its current settings",
            evidence.schema,
            evidence.policy.version
        );
    }
    let source_units: BTreeSet<String> =
        evidence.source_units.iter().map(|unit| unit.name.clone()).collect();
    if source_units.len() != evidence.source_units.len() || &source_units != expected_units {
        bail!("Coverage evidence does not cover exactly the source split units");
    }
    let observations = ObservationIndex::load_enclosed_for_run(
        evidence.identifications,
        &evidence.source,
        &evidence.target,
        source,
        target,
        expected_units,
    )?;
    evidence.identifications = observations.report().clone();
    Ok((evidence, observations))
}

fn persist_observations(
    ctx: &BuildContext,
    observations: &ObservationIndex,
) -> Result<ObservationReference> {
    observations.persist(&ctx.output)
}

/// What a coverage candidate offers, carried from preparation into the trial.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct Proposal {
    pub policy_version: u32,
    pub source_code_bytes: u64,
    #[serde(default)]
    pub required_extracts: Vec<RequiredExtract>,
    /// Extract obligations for every unit any joint alternative could write.
    /// A transaction carries exactly the union for the units it actually
    /// writes, so choosing one alternative cannot silently omit a neighbour's
    /// required asset or publish an unrelated alternative's config edits.
    #[serde(default)]
    pub unit_extracts: BTreeMap<String, Vec<RequiredExtract>>,
    /// The observation that led to this proposal. It survives a trial refusal,
    /// independently of the alternative that happened to be attempted.
    pub identification: UnitIdentification,
    pub observation: ObservationReference,
    /// Each carries its own transaction, and with it the exact before-state of
    /// every unit it reads or writes.
    pub alternatives: Vec<Alternative>,
}

/// How coverage records one applied transaction in [`Applied::record`]: enough
/// to replay its certificate against the observations it was proved with.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct AppliedRecord {
    pub observation: ObservationReference,
    pub alternative: Alternative,
    #[serde(default)]
    pub unit_extracts: BTreeMap<String, Vec<RequiredExtract>>,
}

fn transaction_extracts(
    unit: &str,
    required: &[RequiredExtract],
    by_unit: &BTreeMap<String, Vec<RequiredExtract>>,
    transaction: &OwnershipTransaction,
) -> Result<Vec<RequiredExtract>> {
    if by_unit.is_empty() {
        return Ok(required.to_vec()); // historical schema-4 proposals
    }
    if by_unit.get(unit).map(Vec::as_slice) != Some(required) {
        bail!(ValidationError(format!("{unit}'s required extracts changed in its proposal")));
    }
    // Individual alternatives preserve the source report's order. Joint
    // alternatives use a canonical union across their written members.
    if transaction.writes().count() == 1 {
        return Ok(required.to_vec());
    }
    let mut found = BTreeMap::new();
    for name in transaction.writes() {
        let entries = by_unit.get(name).ok_or_else(|| {
            ValidationError(format!("transaction writes {name} without its extract inventory"))
        })?;
        for entry in entries {
            found.insert(serde_json::to_string(entry)?, entry.clone());
        }
    }
    Ok(found.into_values().collect())
}

fn compare_candidates(left: &Candidate, right: &Candidate) -> Ordering {
    let best = |candidate: &Candidate| {
        proposal_of(candidate)
            .expect("fresh coverage candidate must contain a valid proposal")
            .alternatives
            .into_iter()
            .next()
            .expect("fresh coverage candidate must contain an alternative")
    };
    let left_best = best(left);
    let right_best = best(right);
    (
        Reverse(left_best.ownership.complete_membership),
        Reverse(left_best.ownership.supported_edges),
        Reverse(left_best.ownership.independent_members),
        left_best.ownership.padding_bytes,
        Reverse(left_best.gained_bytes),
    )
        .cmp(&(
            Reverse(right_best.ownership.complete_membership),
            Reverse(right_best.ownership.supported_edges),
            Reverse(right_best.ownership.independent_members),
            right_best.ownership.padding_bytes,
            Reverse(right_best.gained_bytes),
        ))
        .then_with(|| left.name.cmp(&right.name))
}

fn extract_inventory(
    alternatives: &[Alternative],
    units: &BTreeMap<String, &CoverageUnit>,
) -> BTreeMap<String, Vec<RequiredExtract>> {
    alternatives
        .iter()
        .flat_map(|alternative| alternative.transaction.writes())
        .filter_map(|name| {
            units.get(name).map(|unit| (name.to_string(), unit.required_extracts.clone()))
        })
        .collect()
}

/// What preparation found, beyond the candidates themselves.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct Inventory {
    pub evidence_schema: u32,
    pub source: String,
    pub target: String,
    pub source_units: usize,
    pub baseline_represented: usize,
    pub missing: usize,
    /// Candidates that extend a unit which already holds a block, rather than
    /// giving one to a unit with none.
    #[serde(default)]
    pub refinements: usize,
    /// What each unit owned when this stage started, in bytes across every
    /// section. The immutable reference for the whole run: a unit given a block
    /// in round one and extended in round three is one new unit and one total
    /// gain, not a new unit and then a refinement of somebody else's work.
    #[serde(default)]
    pub baseline_bytes: BTreeMap<String, u32>,
    /// Every unit and why it did or did not produce a candidate.
    pub dispositions: BTreeMap<String, String>,
    /// Content-addressed complete observation inventory. The report itself is
    /// stored once beside preparation; summaries and proposals bind to it by
    /// digest.
    pub observation: ObservationReference,
    /// Unit-level diagnostics are small enough to keep in summaries. Function
    /// attributions remain in the content-addressed artifact.
    pub identifications: Vec<UnitIdentification>,
}

impl Stage for Coverage {
    fn name(&self) -> &'static str { "coverage" }

    fn scopes(&self, candidate: &Candidate) -> Result<BTreeSet<MutationScope>> {
        let proposal = proposal_of(candidate)?;
        let mut scopes = BTreeSet::new();
        for alternative in &proposal.alternatives {
            scopes.extend(transaction_scopes(&alternative.transaction));
        }
        Ok(scopes)
    }

    fn is_reserved(
        &self,
        candidate: &Candidate,
        reserved: &BTreeSet<MutationScope>,
    ) -> Result<bool> {
        let proposal = proposal_of(candidate)?;
        Ok(proposal.alternatives.iter().all(|alternative| {
            transaction_scopes(&alternative.transaction)
                .iter()
                .any(|scope| scope.conflicts_with(reserved))
        }))
    }

    fn accepted_scopes(&self, _candidates: &[Candidate]) -> Result<BTreeSet<MutationScope>> {
        // The chosen transaction, including its neighbours, is recorded in
        // `applied`; alternatives that were never applied reserve nothing.
        Ok(BTreeSet::new())
    }

    fn applied_scopes(&self, entry: &Applied) -> Result<BTreeSet<MutationScope>> {
        let record: AppliedRecord = serde_json::from_value(entry.record.clone())?;
        let transaction = &record.alternative.transaction;
        let writes: Vec<String> = transaction.writes().map(str::to_string).collect();
        if writes != entry.units {
            bail!(ValidationError(format!(
                "Applied transaction record for {} does not describe its writes",
                entry.unit
            )));
        }
        let mut scopes = transaction_scopes(transaction);
        scopes.extend(read_dependency_scopes(transaction));
        Ok(scopes)
    }

    fn prepare(&self, ctx: &BuildContext, limit: Option<usize>) -> Result<Prepared> {
        std::fs::create_dir_all(&ctx.output)?;
        let baseline = ctx.build(None)?;

        let source_blocks =
            Splits::read(&ctx.root.join("config").join(&ctx.source).join("splits.txt"))?.blocks;
        let expected_units = source_blocks.keys().cloned().collect();
        let evidence = generate_evidence(ctx)?;
        let (evidence, observations) =
            validate_evidence(evidence, &expected_units, &ctx.source, &ctx.target)?;
        let observation = persist_observations(ctx, &observations)?;
        let _ = std::fs::remove_file(ctx.output.join("coverage-evidence.json"));

        let target_blocks = Splits::read(&splits_path(ctx))?.blocks;

        // An autogenerated unit is dtk's own placeholder, not a source file.
        let source_units: Vec<&CoverageUnit> =
            evidence.source_units.iter().filter(|unit| !unit.autogenerated).collect();
        let by_name: BTreeMap<String, &CoverageUnit> =
            source_units.iter().map(|unit| (unit.name.clone(), *unit)).collect();
        let (mut joint, run_diagnostics) =
            alternatives::joint_runs(&by_name, &target_blocks, &observations);
        let identification_by_name: BTreeMap<&str, &UnitIdentification> = evidence
            .identifications
            .units
            .iter()
            .map(|identification| (identification.unit.as_str(), identification))
            .collect();
        let missing: Vec<&&CoverageUnit> =
            source_units.iter().filter(|unit| !target_blocks.contains_key(&unit.name)).collect();

        // Every unit, not only the ones with no block at all. A unit holding a
        // short or wrong split is the case a cross-version migration produces
        // most often, and skipping it meant the first fragment a unit ever
        // claimed was also its last. What keeps this honest is that an
        // alternative now carries the unit's complete body and has to claim
        // ground it does not already hold, so a unit with nothing to gain
        // produces nothing to try.
        let mut dispositions = BTreeMap::new();
        let mut candidates: Vec<Candidate> = Vec::new();
        let mut refinements = 0;
        for unit in &source_units {
            let mut found =
                alternatives::build(unit, &target_blocks, &by_name, &source_blocks, &observations);
            alternatives::add_joint(&mut found, joint.remove(&unit.name).unwrap_or_default());
            let represented = target_blocks.contains_key(&unit.name);
            dispositions
                .insert(unit.name.clone(), alternatives::disposition(unit, &found, represented));
            if found.is_empty() {
                continue;
            }
            refinements += usize::from(represented);
            let proposal = Proposal {
                policy_version: POLICY_VERSION,
                source_code_bytes: unit.code_bytes,
                required_extracts: unit.required_extracts.clone(),
                unit_extracts: extract_inventory(&found, &by_name),
                identification: (*identification_by_name.get(unit.name.as_str()).with_context(
                    || format!("Coverage evidence has no identification for {}", unit.name),
                )?)
                .clone(),
                observation: observation.clone(),
                alternatives: found,
            };
            candidates.push(Candidate {
                name: unit.name.clone(),
                evidence: serde_json::to_value(proposal)?,
            });
        }
        candidates.sort_by(compare_candidates);
        let mut chosen = candidates;
        if let Some(limit) = limit {
            chosen.truncate(limit);
        }

        let represented =
            source_units.iter().filter(|unit| target_blocks.contains_key(&unit.name)).count();
        let inventory = Inventory {
            evidence_schema: evidence.schema,
            source: evidence.source.clone(),
            target: evidence.target.clone(),
            source_units: source_units.len(),
            baseline_represented: represented,
            missing: missing.len(),
            refinements,
            baseline_bytes: target_blocks
                .iter()
                .map(|(name, lines)| (name.clone(), body_bytes(lines)))
                .collect(),
            dispositions,
            observation,
            identifications: evidence.identifications.units.clone(),
        };

        // Audited, not evaluated: a unit that already owns a range counts as
        // represented, so no stage will look for its real one. Reporting is the
        // whole contribution — repair needs the range to be separately
        // determinable, which this cannot decide.
        let stunted = audit::stunted_splits(
            &target_blocks,
            &audit::load_blocks(&ctx.root, &ctx.source, crate::project::config::DOL_NAME)?,
            ".text",
            audit::STUNTED_RATIO,
        );

        let mut extra = serde_json::Map::new();
        extra.insert("inventory".into(), serde_json::to_value(&inventory)?);
        extra.insert("policy".into(), serde_json::to_value(&evidence.policy)?);
        extra.insert("stunted_splits".into(), serde_json::to_value(&stunted)?);
        extra.insert("joint_run_diagnostics".into(), serde_json::to_value(run_diagnostics)?);
        Ok(Prepared {
            candidates: chosen,
            baseline,
            events: Vec::new(),
            extra,
            permitted: Default::default(),
        })
    }

    fn writes(&self, candidate: &Candidate) -> Result<BTreeSet<String>> {
        let proposal = proposal_of(candidate)?;
        let mut units = BTreeSet::from([candidate.name.clone()]);
        for alternative in &proposal.alternatives {
            units.extend(alternative.transaction.writes().map(str::to_string));
        }
        Ok(units)
    }

    fn footprint(&self, candidate: &Candidate) -> Result<Footprint> {
        // Every alternative, not only the first: a fallback that touches a
        // neighbour is as much a dependency as the preferred choice.
        let proposal = proposal_of(candidate)?;
        let mut footprint = Footprint::of(&candidate.name);
        for alternative in &proposal.alternatives {
            let transaction = &alternative.transaction;
            footprint.units.extend(transaction.touched().map(str::to_string));
            footprint.intervals.extend(transaction.transfers.iter().map(|transfer| {
                let (start, end) = transfer.range();
                (transfer.section.clone(), start, end)
            }));
        }
        Ok(footprint)
    }

    fn evaluate(
        &self,
        ctx: &BuildContext,
        prepared: &Prepared,
        candidates: &[Candidate],
        preferred: &Selections,
    ) -> Result<Outcome> {
        let names: BTreeSet<&str> = candidates.iter().map(|c| c.name.as_str()).collect();
        if names.len() != candidates.len() {
            bail!("Duplicate coverage candidate names");
        }
        let splits_file = splits_path(ctx);
        let config_file = config_path(ctx);
        let mut splits_owned = Owned::take(&splits_file)?;
        let mut config_owned = Owned::take(&config_file)?;
        let mut splits = Splits::parse(&String::from_utf8(splits_owned.original().to_vec())?)?;

        let mut report = ctx.build(None)?;
        let starting_complete = report.measures.complete_code;
        let mut accepted: Vec<Candidate> = Vec::new();
        let mut selections = Selections::new();
        let mut applied: Vec<Applied> = Vec::new();
        let mut events: Vec<Event> = Vec::new();
        let mut observations = Observations::default();
        // Every alternative each unit has already been asked about, so that a
        // later round can tell a genuinely new proposal from the one that was
        // just refused.
        let mut tried: BTreeMap<String, BTreeSet<String>> = BTreeMap::new();

        // One pass over exactly what was handed over. Finding *new* work is the
        // coordinator's to ask for, between rounds, in the one workspace that
        // holds every batch's result — a worker that went looking here would be
        // deciding the fate of units another worker is holding at the time.
        for candidate in candidates {
            let proposal = proposal_of(candidate)?;
            let index = observations.load(&proposal.observation, ctx)?;
            // A rollback point for the configuration, in case none of this
            // candidate's alternatives survives.
            let config_before = config_owned.current().to_vec();
            // Try the alternative a worker already proved first.
            let mut ordered: Vec<&Alternative> = proposal.alternatives.iter().collect();
            if let Some(wanted) = preferred.get(&candidate.name) {
                ordered.sort_by_key(|alternative| &alternative.id != wanted);
            }

            let seen = tried.entry(candidate.name.clone()).or_default();
            let mut chosen: Option<&Alternative> = None;
            for alternative in ordered {
                seen.insert(alternative.retry_key());
                let restore = splits.clone();
                let required = transaction_extracts(
                    &candidate.name,
                    &proposal.required_extracts,
                    &proposal.unit_extracts,
                    &alternative.transaction,
                )?;
                let rendered =
                    extracts::render(&String::from_utf8(config_before.clone())?, &required)?;
                config_owned.write(rendered.as_bytes())?;
                let trial = Trial {
                    candidate,
                    alternative,
                    proposal: &proposal,
                    observations: index,
                    permitted: &prepared.permitted,
                };
                match trial.run(ctx, &mut splits_owned, &mut splits, &report, starting_complete) {
                    Ok(tested) => {
                        chosen = Some(alternative);
                        report = tested;
                        break;
                    }
                    Err(error) if is_trial_failure(&error) => {
                        splits = restore;
                        write(&mut splits_owned, &splits)?;
                        let refusal = Refusal::from_error(&error);
                        events.push(
                            Event::new(&candidate.name, "rejected")
                                .because(format!("{}: {error:#}", refusal.kind.legacy_category()))
                                .about(&alternative.id)
                                .refused(refusal),
                        );
                    }
                    Err(error) => return Err(error),
                }
            }

            match chosen {
                Some(alternative) => {
                    let transaction = &alternative.transaction;
                    let units: Vec<String> = transaction.writes().map(str::to_string).collect();
                    accepted.push(candidate.clone());
                    selections.insert(candidate.name.clone(), alternative.id.clone());
                    applied.push(Applied {
                        unit: candidate.name.clone(),
                        id: alternative.id.clone(),
                        units: units.clone(),
                        record: serde_json::to_value(AppliedRecord {
                            observation: proposal.observation.clone(),
                            alternative: alternative.clone(),
                            unit_extracts: proposal.unit_extracts.clone(),
                        })?,
                    });
                    events.push(
                        Event::new(&candidate.name, "accepted")
                            .because(format!(
                                "{} gaining {} bytes; transaction {} writes {}",
                                alternative.evidence,
                                alternative.gained_bytes,
                                short(&transaction.id),
                                units.join(", ")
                            ))
                            .about(&alternative.id),
                    );
                }
                None => {
                    // Take back this candidate's extract entries; nothing needs
                    // them now.
                    config_owned.write(&config_before)?;
                }
            }
        }
        write(&mut splits_owned, &splits)?;

        let taken: BTreeSet<&str> = accepted.iter().map(|c| c.name.as_str()).collect();
        let deferred: Vec<Candidate> =
            candidates.iter().filter(|c| !taken.contains(c.name.as_str())).cloned().collect();

        let final_report = self.validate_selected(
            ctx,
            &accepted,
            &selections,
            &applied,
            &BTreeSet::new(),
            &mut observations,
        )?;
        if regresses(&report, &final_report) {
            bail!("Final coverage report regressed after validation");
        }
        splits_owned.commit();
        config_owned.commit();
        Ok(Outcome {
            accepted,
            deferred,
            tried,
            selections,
            events,
            report: final_report,
            validation: VALIDATION.to_string(),
            applied,
        })
    }

    fn rediscover(
        &self,
        ctx: &BuildContext,
        prepared: &Prepared,
        tried: &Tried,
    ) -> Result<Option<Rediscovery>> {
        Ok(Some(revisit(ctx, &prepared.permitted, tried)?))
    }

    fn validate(
        &self,
        ctx: &BuildContext,
        accepted: &[Candidate],
        _prepared: &Prepared,
        selections: &Selections,
        applied: &[Applied],
    ) -> Result<Report> {
        self.validate_selected(
            ctx,
            accepted,
            selections,
            applied,
            &BTreeSet::new(),
            &mut Observations::default(),
        )
    }

    fn validate_final(
        &self,
        ctx: &BuildContext,
        accepted: &[Candidate],
        _prepared: &Prepared,
        selections: &Selections,
        applied: &[Applied],
        certificates: &FinalCertificates,
    ) -> Result<Report> {
        self.validate_selected(
            ctx,
            accepted,
            selections,
            applied,
            &certificates.source_linked,
            &mut Observations::default(),
        )
    }

    fn artifacts(
        &self,
        prepared: &Prepared,
        result: &crate::run::StageResult,
    ) -> Result<Vec<(String, Vec<u8>)>> {
        let summary = summarize(prepared, result)?;
        Ok(vec![
            ("coverage.json".to_string(), serde_json::to_vec_pretty(&summary)?),
            ("coverage.md".to_string(), markdown(&summary).into_bytes()),
        ])
    }
}

/// Observation reports already loaded, by digest. A report is tens of
/// megabytes and every candidate in a round refers to the same one.
#[derive(Default)]
struct Observations(BTreeMap<String, ObservationIndex>);

impl Observations {
    fn load(
        &mut self,
        reference: &ObservationReference,
        ctx: &BuildContext,
    ) -> Result<&ObservationIndex> {
        if !self.0.contains_key(&reference.sha256) {
            let index = load_reference(reference, &ctx.source, &ctx.target)?;
            self.0.insert(reference.sha256.clone(), index);
        }
        Ok(&self.0[&reference.sha256])
    }
}

fn short(id: &str) -> &str { &id[..id.len().min(16)] }

impl Coverage {
    /// Rechecks that the project really is the result of the transactions
    /// integration applied, in the order it applied them, then that the build
    /// agrees.
    ///
    /// The history is walked backwards from the project as it stands: each
    /// transaction's bodies must be exactly what is there, its certificate
    /// must replay against its own observations, and undoing it must leave
    /// exactly what the one before it wrote. A superseded refinement or a
    /// neighbour narrowed by an earlier round is checked like any other change,
    /// rather than disappearing because no final candidate still carries it.
    fn validate_selected(
        &self,
        ctx: &BuildContext,
        accepted: &[Candidate],
        selections: &Selections,
        applied: &[Applied],
        final_source_linked: &BTreeSet<String>,
        observations: &mut Observations,
    ) -> Result<Report> {
        let expected: BTreeMap<&str, Proposal> = accepted
            .iter()
            .map(|candidate| Ok((candidate.name.as_str(), proposal_of(candidate)?)))
            .collect::<Result<_>>()?;
        let chosen: BTreeSet<&str> = selections.keys().map(String::as_str).collect();
        if chosen != expected.keys().copied().collect() {
            bail!(ValidationError(
                "Coverage selection does not match the accepted candidates".into()
            ));
        }

        let records: Vec<AppliedRecord> = applied
            .iter()
            .map(|entry| {
                let record: AppliedRecord = serde_json::from_value(entry.record.clone())
                    .with_context(|| format!("Malformed applied transaction for {}", entry.unit))?;
                let transaction = &record.alternative.transaction;
                if record.alternative.id != entry.id
                    || transaction.writes().collect::<Vec<_>>() != entry.units
                {
                    bail!(ValidationError(format!(
                        "Applied transaction record for {} does not describe itself",
                        entry.unit
                    )));
                }
                Ok(record)
            })
            .collect::<Result<_>>()?;
        for (name, id) in selections {
            let proposal = &expected[name.as_str()];
            if !proposal.alternatives.iter().any(|a| &a.id == id) {
                bail!(ValidationError(format!("Unknown coverage alternative for {name}")));
            }
            // The selection has to be the last thing applied for its unit, or
            // the proposal stored beside it describes a state that was later
            // replaced.
            if applied.iter().rev().find(|entry| &entry.unit == name).map(|e| &e.id) != Some(id) {
                bail!(ValidationError(format!(
                    "Coverage selection for {name} is not its last applied transaction"
                )));
            }
        }

        let transactions: Vec<&OwnershipTransaction> =
            records.iter().map(|record| &record.alternative.transaction).collect();
        let final_blocks = Splits::read(&splits_path(ctx))?.blocks;
        for transaction in &transactions {
            validate_read_dependencies(transaction, &final_blocks)?;
        }
        let mut blocks = coverage_history_projection(&final_blocks, &transactions)?;
        for (entry, record) in applied.iter().zip(&records).rev() {
            let index = observations.load(&record.observation, ctx)?;
            if !record.unit_extracts.is_empty() {
                let required = transaction_extracts(
                    &entry.unit,
                    record.unit_extracts.get(&entry.unit).map(Vec::as_slice).unwrap_or_default(),
                    &record.unit_extracts,
                    &record.alternative.transaction,
                )?;
                if required != record.alternative.transaction.required_extracts {
                    bail!(ValidationError(format!(
                        "Applied transaction for {} has incomplete required extracts",
                        entry.unit
                    )));
                }
            }
            validate_certificate(&entry.unit, &record.observation, &record.alternative, index)?;
            validate_read_dependencies(&record.alternative.transaction, &blocks)?;
            record.alternative.transaction.undo(&mut blocks).map_err(|error| {
                ValidationError(format!(
                    "Coverage split for {} changed after selection: {error:#}",
                    entry.unit
                ))
            })?;
        }

        let report = ctx.build(None)?;
        let written: BTreeSet<&str> = applied
            .iter()
            .flat_map(|entry| entry.units.iter().map(String::as_str))
            .filter(|unit| !final_source_linked.contains(*unit))
            .collect();
        validate_extracted_inputs(ctx, &written, &report)?;
        let required: Vec<&RequiredExtract> = records
            .iter()
            .flat_map(|record| record.alternative.transaction.required_extracts.iter())
            .collect();
        validate_required_extracts(ctx, &required)?;
        Ok(report)
    }
}

/// One alternative, about to be tried.
struct Trial<'a> {
    candidate: &'a Candidate,
    alternative: &'a Alternative,
    proposal: &'a Proposal,
    observations: &'a ObservationIndex,
    permitted: &'a Permitted,
}

impl Trial<'_> {
    /// Applies the alternative's transaction and asks the build whether it
    /// holds. Everything that can be refused without a build is refused first.
    fn run(
        &self,
        ctx: &BuildContext,
        owned: &mut Owned,
        splits: &mut Splits,
        baseline: &Report,
        starting_complete: u64,
    ) -> Result<Report> {
        let name = self.candidate.name.as_str();
        let transaction = &self.alternative.transaction;
        // A transaction may only write units this run lets the stage change.
        // Refusing the whole of it is the only honest option: applying the
        // candidate without the neighbour it depends on is a different change.
        if let Some(unit) = transaction.writes().find(|unit| !self.permitted.allows(unit)) {
            bail!(ValidationError(format!(
                "{name} requires changing {unit}, which this run does not permit"
            )));
        }
        if let Some(member) = transaction.members.iter().find(|member| {
            changes_data(member.before.as_deref(), &member.after)
                && !self.permitted.allows_data(&member.unit)
        }) {
            bail!(ValidationError(format!(
                "{name} requires changing {}'s certified data, which this run does not permit",
                member.unit
            )));
        }
        if transaction.required_extracts
            != transaction_extracts(
                name,
                &self.proposal.required_extracts,
                &self.proposal.unit_extracts,
                transaction,
            )?
        {
            bail!(ValidationError(format!(
                "transaction for {name} carries different required extracts from its proposal"
            )));
        }
        validate_certificate(
            name,
            &self.proposal.observation,
            self.alternative,
            self.observations,
        )?;
        transaction.apply(&mut splits.blocks)?;
        write(owned, splits)?;

        let tested = ctx.trial_build()?;
        let names: BTreeSet<&str> = transaction.writes().collect();
        validate_extracted_inputs(ctx, &names, &tested)?;
        validate_required_extracts(ctx, &transaction.required_extracts.iter().collect::<Vec<_>>())?;
        if regresses(baseline, &tested) {
            bail!(ValidationError("coverage candidate regresses an existing unit".into()));
        }
        // A coverage range must not quietly enable a source file: that is
        // verification's claim to make, with a different gate behind it.
        if tested.measures.complete_code < starting_complete {
            bail!(ValidationError("coverage candidate reduces source-linked code".into()));
        }
        Ok(tested)
    }
}

/// Replays an alternative's certificates against the observations it cites.
///
/// State is not this function's concern — whether the project holds the
/// transaction's before- or after-state is checked by applying or undoing it.
/// What is checked here is that the transaction is the one its evidence
/// justifies: derived under this policy from these observations, with every
/// receiving unit's new ground independently supported.
fn validate_certificate(
    unit: &str,
    observation: &ObservationReference,
    alternative: &Alternative,
    observations: &ObservationIndex,
) -> Result<()> {
    let transaction: &OwnershipTransaction = &alternative.transaction;
    if observations.digest() != observation.sha256
        || transaction.observation_sha256 != observation.sha256
        || alternative.ownership.observation_sha256 != observation.sha256
    {
        bail!(ValidationError(format!("Ownership observations changed for {unit}")));
    }
    transaction.validate()?;
    if alternative.id != transaction.id
        || transaction.member(unit).map(|member| &member.after) != Some(&alternative.lines)
    {
        bail!(ValidationError(format!(
            "Alternative {} for {unit} does not match its transaction",
            alternative.id
        )));
    }
    if transaction.policy != policy_digest() {
        bail!(ValidationError(format!(
            "Transaction {} for {unit} was derived under a different coverage policy",
            short(&transaction.id)
        )));
    }
    // Coverage only ever moves ground between units or claims unowned ground;
    // giving ground up to nobody is a correction it has no evidence for.
    if !transaction.releases.is_empty() {
        bail!(ValidationError(format!(
            "transaction refused: {unit} would release ground coverage cannot justify"
        )));
    }

    let others: BTreeSet<&str> =
        transaction.receivers().into_iter().filter(|receiver| *receiver != unit).collect();
    if others != alternative.receiver_ownership.keys().map(String::as_str).collect() {
        bail!(ValidationError(format!(
            "Ownership certificate for {unit} alternative {} does not cover every receiver",
            alternative.id
        )));
    }
    for (member, recorded) in std::iter::once((unit, &alternative.ownership))
        .chain(alternative.receiver_ownership.iter().map(|(name, value)| (name.as_str(), value)))
    {
        let actual = assess_member(observations, transaction, member).ok_or_else(|| {
            ValidationError(format!("{member} is not written by {unit} alternative"))
        })?;
        if &actual != recorded {
            bail!(ValidationError(format!(
                "Ownership certificate is stale for {member} in {unit} alternative {}",
                alternative.id
            )));
        }
        if !actual.permits_automatic_claim() {
            bail!(ValidationError(format!(
                "Ownership evidence does not support {member} in {unit} alternative {}",
                alternative.id
            )));
        }
    }
    Ok(())
}

/// Whether the stage would offer this unit a candidate.
///
/// One rule, used by preparation, by the revisit loop, and by calibration —
/// which otherwise measures a population the pipeline does not have. It used to
/// be "has no block at all"; a unit holding a short block is now eligible too,
/// and the only thing that makes a unit ineligible is having nothing left to
/// claim.
pub fn offers_candidate(alternatives: &[Alternative]) -> bool { !alternatives.is_empty() }

/// Regenerates evidence after something was accepted, and returns every unit
/// that now has a proposal nobody has refused yet.
///
/// The cascade this exists for runs in both directions. A unit refused because
/// the ground it wanted was unaccounted for, or because its run had no boundary
/// either side, may be answerable once a neighbour lands — and so may a unit
/// that was *never a candidate*, because the boundary that gives it its first
/// usable evidence only came into existence just now. A unit that was accepted
/// with part of itself can likewise be extended again. All three are facts
/// about the neighbourhood, and the neighbourhood is what just changed, so the
/// whole eligible set is reconsidered rather than only the list that failed.
///
/// What keeps it from looping: a unit whose alternatives have only trial keys
/// already tried is dropped. A new report digest alone is not a new trial;
/// relevant before/after bodies, read dependencies or evidence must differ.
fn revisit(
    ctx: &BuildContext,
    permitted: &Permitted,
    tried: &BTreeMap<String, BTreeSet<String>>,
) -> Result<Rediscovery> {
    let source_blocks =
        Splits::read(&ctx.root.join("config").join(&ctx.source).join("splits.txt"))?.blocks;
    let expected_units = source_blocks.keys().cloned().collect();
    let evidence = generate_evidence(ctx)?;
    let (evidence, observations) =
        validate_evidence(evidence, &expected_units, &ctx.source, &ctx.target)?;
    let observation = persist_observations(ctx, &observations)?;
    let _ = std::fs::remove_file(ctx.output.join("coverage-evidence.json"));
    let target_blocks = Splits::read(&splits_path(ctx))?.blocks;
    let by_name: BTreeMap<String, &CoverageUnit> = evidence
        .source_units
        .iter()
        .filter(|unit| !unit.autogenerated)
        .map(|unit| (unit.name.clone(), unit))
        .collect();
    let (mut joint, _) = alternatives::joint_runs(&by_name, &target_blocks, &observations);
    let identification_by_name: BTreeMap<&str, &UnitIdentification> = evidence
        .identifications
        .units
        .iter()
        .map(|identification| (identification.unit.as_str(), identification))
        .collect();

    let mut next = Vec::new();
    let mut skipped_unchanged = 0;
    for (name, unit) in &by_name {
        if !permitted.allows(name) {
            continue;
        }
        let mut found =
            alternatives::build(unit, &target_blocks, &by_name, &source_blocks, &observations);
        alternatives::add_joint(&mut found, joint.remove(name).unwrap_or_default());
        let (found, skipped) = untried(found, tried.get(name));
        skipped_unchanged += skipped;
        if found.is_empty() {
            continue;
        }
        let proposal = Proposal {
            policy_version: POLICY_VERSION,
            source_code_bytes: unit.code_bytes,
            required_extracts: unit.required_extracts.clone(),
            unit_extracts: extract_inventory(&found, &by_name),
            identification: (*identification_by_name
                .get(name.as_str())
                .with_context(|| format!("Coverage evidence has no identification for {name}"))?)
            .clone(),
            observation: observation.clone(),
            alternatives: found,
        };
        next.push(Candidate { name: name.clone(), evidence: serde_json::to_value(proposal)? });
    }
    next.sort_by(compare_candidates);
    Ok(Rediscovery { candidates: next, skipped_unchanged })
}

/// Only pass genuinely new transactions to the next evaluation round. A new
/// alternative alongside an old refusal must not cause the old build to run
/// again just because the proposal as a whole is new.
fn untried(
    mut alternatives: Vec<Alternative>,
    tried: Option<&BTreeSet<String>>,
) -> (Vec<Alternative>, usize) {
    let before = alternatives.len();
    if let Some(tried) = tried {
        alternatives.retain(|alternative| !tried.contains(&alternative.retry_key()));
    }
    let skipped = before - alternatives.len();
    (alternatives, skipped)
}

/// Writes one alternative into a set of split blocks, as a trial would.
///
/// Every unit the alternative's transaction names is *replaced*, not added to,
/// and all of them change together or none does. Calibration applies proposals
/// through this rather than modelling it, because a measured recovery is only
/// worth reporting if it is a recovery the migration could actually perform.
pub fn apply_alternative(
    blocks: &mut IndexMap<String, Vec<String>>,
    unit: &str,
    alternative: &Alternative,
) -> Result<()> {
    let transaction = &alternative.transaction;
    if transaction.member(unit).map(|member| &member.after) != Some(&alternative.lines) {
        bail!(ValidationError(format!(
            "transaction refused: alternative {} does not write {unit}",
            alternative.id
        )));
    }
    transaction.apply(blocks)
}

/// Requires each named unit to still link from its *extracted* object.
///
/// This is what keeps the stage honest about what it proved. If a candidate's
/// compiled source object had been linked instead, the retail hash would be
/// saying something about that source, and this stage has no evidence for it.
fn validate_extracted_inputs(
    ctx: &BuildContext,
    names: &BTreeSet<&str>,
    report: &Report,
) -> Result<()> {
    let args =
        vec!["-t".to_string(), "inputs".to_string(), format!("build/{}/main.elf", ctx.target)];
    let output = ctx
        .run(&ctx.tools.ninja.clone(), &args, true, None)
        .map_err(anyhow::Error::new)
        .context("Failed to list the linker's inputs")?;
    let inputs: BTreeSet<String> =
        output.lines().filter(|line| !line.trim().is_empty()).map(|p| normalize(ctx, p)).collect();

    let objdiff = ObjdiffConfig::read(&ctx.root.join("objdiff.json"))?;
    let by_target: BTreeMap<String, &crate::project::report::ObjdiffUnit> = objdiff
        .units
        .iter()
        .filter_map(|unit| Some((normalize(ctx, unit.target_path.as_deref()?), unit)))
        .collect();
    let units = report.by_source_name();

    for name in names {
        let object = format!("build/{}/obj/{}.o", ctx.target, strip_extension(name));
        let expected = normalize(ctx, &object);
        let Some(unit) = by_target.get(&expected).filter(|_| inputs.contains(&expected)) else {
            bail!(ValidationError(format!(
                "{name}'s extracted target object is not an input to main.elf"
            )));
        };
        if let Some(base) = &unit.base_path
            && inputs.contains(&normalize(ctx, base))
        {
            bail!(ValidationError(format!(
                "{name}'s compiled source object was enabled during coverage"
            )));
        }
        if units.get(name).and_then(|unit| unit.metadata.complete) == Some(true) {
            bail!(ValidationError(format!("{name} was marked complete during coverage")));
        }
    }
    Ok(())
}

/// Requires each extract entry to have actually produced its files.
fn validate_required_extracts(ctx: &BuildContext, extracts: &[&RequiredExtract]) -> Result<()> {
    for extract in extracts {
        for (field, value, directory) in [
            ("binary", &extract.binary, "bin"),
            ("header", &extract.header, "include"),
            ("relocations", &extract.relocations, "bin"),
        ] {
            let Some(relative) = value else { continue };
            extracts::check_path(relative)?;
            let path = ctx.root.join("build").join(&ctx.target).join(directory).join(relative);
            if !path.is_file() {
                bail!(ValidationError(format!(
                    "required extract did not generate {field} output: {relative}"
                )));
            }
        }
        // The source include expects a particular name; a header that does not
        // declare it would fail to compile later, far from here.
        if let (Some(header), Some(rename)) = (&extract.header, &extract.rename)
            && extract.header_type.as_deref() != Some("none")
        {
            let path = ctx.root.join("build").join(&ctx.target).join("include").join(header);
            let text = std::fs::read_to_string(&path).unwrap_or_default();
            if !text.contains(rename) {
                bail!(ValidationError(format!(
                    "required extract header {header} does not declare {rename}"
                )));
            }
        }
    }
    Ok(())
}

/// Compatibility check for historical refusal categories in tests.
#[cfg(test)]
fn failure_category(error: &anyhow::Error) -> &'static str {
    Refusal::from_error(error).kind.legacy_category()
}

/// A directory of prepared coverage evidence, standing in for the matcher.
///
/// A testing seam, and deliberately a narrow one: everything else in this stage
/// — the trials, the ownership gates, worker batching, publication, resume —
/// runs exactly as it does in a real migration. What it replaces is the one part
/// that needs two analysable binaries to say anything at all, so that the
/// cascade a boundary landing sets off can be exercised without a fixture that
/// reimplements decomp-toolkit.
///
/// Evidence is chosen by how many units the target's splits already name, which
/// is what makes a cascade expressible: `0.json` is what the matcher would say
/// before anything landed, `1.json` what it says once one unit has a block, and
/// so on. A run using this records a digest of the whole directory in its frozen
/// environment, so execution and resume cannot quietly disagree about which
/// world they are in.
const EVIDENCE_DIRECTORY: &str = "DTK_MIGRATE_EVIDENCE_DIR";

pub(crate) fn injected_evidence_dir() -> Option<std::path::PathBuf> {
    std::env::var_os(EVIDENCE_DIRECTORY)
        .filter(|value| !value.is_empty())
        .map(std::path::PathBuf::from)
}

/// A digest over every prepared evidence file, or `None` in a real migration.
pub fn injected_evidence_digest() -> Result<Option<String>> {
    let Some(directory) = injected_evidence_dir() else { return Ok(None) };
    let mut names: Vec<std::path::PathBuf> = std::fs::read_dir(&directory)
        .with_context(|| format!("Failed to read {}", directory.display()))?
        .filter_map(|entry| entry.ok().map(|entry| entry.path()))
        .collect();
    names.sort();
    let mut digest = <sha2::Sha256 as sha2::Digest>::new();
    for path in names {
        sha2::Digest::update(&mut digest, path.file_name().unwrap_or_default().as_encoded_bytes());
        sha2::Digest::update(&mut digest, std::fs::read(&path)?);
    }
    Ok(Some(format!("{:x}", sha2::Digest::finalize(digest))))
}

fn generate_evidence(ctx: &BuildContext) -> Result<CoverageReport> {
    let path = ctx.output.join("coverage-evidence.json");
    match injected_evidence_dir() {
        Some(directory) => {
            // Which world the fixture is in: how much the target already owns.
            let named = Splits::read(&splits_path(ctx))?.blocks.len();
            let prepared = directory.join(format!("{named}.json"));
            std::fs::create_dir_all(&ctx.output)?;
            std::fs::copy(&prepared, &path).with_context(|| {
                format!("Failed to read injected evidence {}", prepared.display())
            })?;
        }
        None => {
            let mut request = crate::matching::Request::new(
                crate::stages::discover::config_path(ctx, &ctx.source),
                crate::stages::discover::config_path(ctx, &ctx.target),
            );
            request.object_root = Some(ctx.root.clone());
            request.outputs.coverage = Some(path.clone());
            crate::matching::run(&request).with_context(|| {
                format!(
                    "Failed to generate coverage evidence from {} and {} in {}",
                    request.source_config,
                    request.target_config,
                    std::env::current_dir()
                        .map_or_else(|_| "<unknown>".into(), |cwd| cwd.display().to_string())
                )
            })?;
        }
    }
    let text = std::fs::read_to_string(&path)
        .with_context(|| format!("Failed to read {}", path.display()))?;
    serde_json::from_str(&text).context("Failed to parse the coverage evidence")
}

fn proposal_of(candidate: &Candidate) -> Result<Proposal> {
    serde_json::from_value(candidate.evidence.clone())
        .with_context(|| format!("Missing coverage proposal for {}", candidate.name))
}

fn splits_path(ctx: &BuildContext) -> std::path::PathBuf {
    ctx.root.join("config").join(&ctx.target).join("splits.txt")
}

fn config_path(ctx: &BuildContext) -> std::path::PathBuf {
    ctx.root.join("config").join(&ctx.target).join("config.yml")
}

fn write(owned: &mut Owned, splits: &Splits) -> Result<()> {
    owned.write(splits.render().as_bytes())
}

fn regresses(before: &Report, after: &Report) -> bool {
    let new = after.by_source_name();
    before.by_source_name().iter().any(|(name, unit)| {
        new.get(name).map(|u| u.matched_code()).unwrap_or(0) < unit.matched_code()
    })
}

fn strip_extension(name: &str) -> &str {
    match name.rfind('.') {
        Some(index) if !name[index..].contains('/') => &name[..index],
        _ => name,
    }
}

/// One spelling for a path, so a Ninja listing and an objdiff entry compare.
fn normalize(ctx: &BuildContext, path: &str) -> String {
    let joined = ctx.root.join(path.replace('\\', "/"));
    let text = joined.to_string_lossy().replace('\\', "/");
    let mut parts: Vec<&str> = Vec::new();
    for part in text.split('/') {
        match part {
            "." => {}
            ".." => {
                parts.pop();
            }
            other => parts.push(other),
        }
    }
    let joined = parts.join("/");
    if cfg!(windows) { joined.to_lowercase() } else { joined }
}

/// The stage's own report, which keeps the four kinds of progress apart.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct Summary {
    pub schema: u32,
    pub source: String,
    pub target: String,
    pub source_units: usize,
    pub baseline_represented: usize,
    pub final_represented: usize,
    pub newly_supported_units: usize,
    /// Units that already had a block and had a boundary moved. Not new TUs.
    #[serde(default)]
    pub refined_units: usize,
    pub newly_assigned_code_bytes: u32,
    pub selected: BTreeMap<String, Alternative>,
    pub dispositions: BTreeMap<String, String>,
    pub observation: ObservationReference,
    pub identifications: Vec<UnitIdentification>,
    pub events: Vec<Event>,
    #[serde(default)]
    pub retry: crate::run::RetryCounts,
    pub metrics: Metrics,
    pub measures: Measures,
    pub stunted_splits: Vec<Stunted>,
    pub validation: String,
    #[serde(default)]
    pub eligible_excluded_by_only: Vec<String>,
    /// Every transaction integration applied, in order, with what it did to
    /// each unit it wrote. A unit's effects are reported per transaction so
    /// that a neighbour's loss stays attached to the change that caused it.
    #[serde(default)]
    pub transactions: Vec<TransactionSummary>,
    /// Bounded run searches unresolved at initial preparation. Later
    /// rediscovery may resolve them; these are observations of the baseline,
    /// not attempted ownership changes.
    #[serde(default)]
    pub joint_run_diagnostics: Vec<alternatives::RunDiagnostic>,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct TransactionSummary {
    pub id: String,
    /// The candidate whose proposal carried it.
    pub candidate: String,
    pub evidence: String,
    pub members: Vec<MemberEffect>,
    /// Owned bytes after minus before, over every member. Zero for a pure
    /// boundary move.
    pub net_bytes: i64,
    /// A later transaction for the same candidate replaced this one. Its
    /// effects on other units still stand unless something else wrote them.
    pub superseded: bool,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct MemberEffect {
    pub unit: String,
    pub gained_bytes: u32,
    pub lost_bytes: u32,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct Metrics {
    pub representation: Representation,
    pub objdiff_matching: BeforeAfter,
    pub configured_source_linkage: BeforeAfter,
    pub verified_source_linkage: VerifiedLinkage,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct Representation {
    pub baseline_tus: usize,
    pub final_tus: usize,
    pub source_tus: usize,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct BeforeAfter {
    pub baseline_code_bytes: u64,
    pub final_code_bytes: u64,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct VerifiedLinkage {
    pub new_units: u32,
    pub new_code_bytes: u64,
    pub reason: String,
}

pub fn summarize(prepared: &Prepared, result: &crate::run::StageResult) -> Result<Summary> {
    let inventory: Inventory = serde_json::from_value(
        prepared.extra.get("inventory").cloned().unwrap_or(serde_json::Value::Null),
    )
    .context("Coverage preparation recorded no inventory")?;
    let stunted: Vec<Stunted> = prepared
        .extra
        .get("stunted_splits")
        .cloned()
        .map(serde_json::from_value)
        .transpose()?
        .unwrap_or_default();
    let joint_run_diagnostics: Vec<alternatives::RunDiagnostic> = prepared
        .extra
        .get("joint_run_diagnostics")
        .cloned()
        .map(serde_json::from_value)
        .transpose()?
        .unwrap_or_default();

    let mut selected: BTreeMap<String, Alternative> = BTreeMap::new();
    for candidate in &result.accepted {
        let Some(id) = result.selections.get(&candidate.name) else { continue };
        let proposal = proposal_of(candidate)?;
        if let Some(alternative) = proposal.alternatives.into_iter().find(|a| &a.id == id) {
            selected.insert(candidate.name.clone(), alternative);
        }
    }
    // Every unit's final body is whatever the last transaction to write it left
    // there — which for a neighbour may be a transaction whose own candidate
    // was later extended again.
    let mut final_bodies: BTreeMap<String, Vec<String>> = BTreeMap::new();
    let mut transactions: Vec<TransactionSummary> = Vec::new();
    for (index, entry) in result.applied.iter().enumerate() {
        let record: AppliedRecord = serde_json::from_value(entry.record.clone())
            .with_context(|| format!("Malformed applied transaction for {}", entry.unit))?;
        let transaction = &record.alternative.transaction;
        for member in &transaction.members {
            final_bodies.insert(member.unit.clone(), member.after.clone());
        }
        transactions.push(TransactionSummary {
            id: transaction.id.clone(),
            candidate: entry.unit.clone(),
            evidence: record.alternative.evidence.clone(),
            members: transaction
                .writes()
                .map(|unit| MemberEffect {
                    unit: unit.to_string(),
                    gained_bytes: transaction.gained_bytes(unit),
                    lost_bytes: transaction.lost_bytes(unit),
                })
                .collect(),
            net_bytes: transaction.net_bytes(),
            superseded: result.applied[index + 1..].iter().any(|later| later.unit == entry.unit),
        });
    }

    // Against the stage's own starting point, never against the workspace as it
    // stands. A unit given a block in one round and grown in the next holds a
    // proposal whose `gained_bytes` measures only that last step, and whose
    // surroundings by then say it was already represented — both of which would
    // report a new translation unit as somebody else's refinement. Ground one
    // unit took from another is a transfer, not new ownership, so the total is
    // net over every unit written.
    let refined: BTreeSet<&String> =
        final_bodies.keys().filter(|name| inventory.baseline_bytes.contains_key(*name)).collect();
    let gained: i64 = final_bodies
        .iter()
        .map(|(name, body)| {
            let started_with = inventory.baseline_bytes.get(name).copied().unwrap_or(0);
            i64::from(body_bytes(body)) - i64::from(started_with)
        })
        .sum();
    let gained = u32::try_from(gained.max(0)).unwrap_or(u32::MAX);

    let mut dispositions = inventory.dispositions.clone();
    for name in final_bodies.keys() {
        dispositions.insert(name.clone(), "revised-by-transaction".into());
    }
    for name in selected.keys() {
        dispositions.insert(name.clone(), "accepted".into());
    }
    for candidate in &result.deferred {
        // The last refusal decides: a preflight refusal is a different answer
        // from a build that failed, and says what would have to change.
        let reason = result
            .events
            .iter()
            .filter(|event| event.unit == candidate.name && event.status == "rejected")
            .filter_map(|event| event.reason.as_deref())
            .next_back();
        let disposition = match reason.and_then(|reason| reason.split(':').next()) {
            None => "deferred",
            Some(
                category @ ("stale-precondition"
                | "dependency-not-permitted"
                | "ownership-preflight"
                | "link-order-cycle"),
            ) => category,
            Some(_) => "build-failure",
        };
        dispositions.insert(candidate.name.clone(), disposition.into());
    }

    // A refinement moves a boundary on a unit the project already had; only a
    // unit that had no block at baseline is newly represented.
    let newly_supported = final_bodies.len() - refined.len();
    let final_represented = inventory.baseline_represented + newly_supported;
    Ok(Summary {
        schema: EVIDENCE_SCHEMA,
        source: inventory.source.clone(),
        target: inventory.target.clone(),
        source_units: inventory.source_units,
        baseline_represented: inventory.baseline_represented,
        final_represented,
        newly_supported_units: newly_supported,
        refined_units: refined.len(),
        newly_assigned_code_bytes: gained,
        metrics: Metrics {
            representation: Representation {
                baseline_tus: inventory.baseline_represented,
                final_tus: final_represented,
                source_tus: inventory.source_units,
            },
            objdiff_matching: BeforeAfter {
                baseline_code_bytes: result.baseline.matched_code,
                final_code_bytes: result.final_measures.matched_code,
            },
            configured_source_linkage: BeforeAfter {
                baseline_code_bytes: result.baseline.complete_code,
                final_code_bytes: result.final_measures.complete_code,
            },
            verified_source_linkage: VerifiedLinkage {
                new_units: 0,
                new_code_bytes: 0,
                reason: "coverage keeps candidate source objects disabled".into(),
            },
        },
        selected,
        dispositions,
        observation: ObservationReference {
            file: format!("preparation/ownership-{}.json", inventory.observation.sha256),
            ..inventory.observation
        },
        identifications: inventory.identifications,
        events: result.events.clone(),
        retry: result.retry.clone(),
        measures: result.final_measures.clone(),
        stunted_splits: stunted,
        validation: result.validation.clone(),
        eligible_excluded_by_only: result.eligible_excluded_by_only.clone(),
        transactions,
        joint_run_diagnostics,
    })
}

pub fn markdown(value: &Summary) -> String {
    let mut lines = vec![
        "# Coverage stage result".to_string(),
        String::new(),
        format!(
            "- Represented source TUs: {} → {} / {}",
            value.baseline_represented, value.final_represented, value.source_units
        ),
        format!("- Newly supported TUs: {}", value.newly_supported_units),
        format!("- Refined TUs (boundary moved, already represented): {}", value.refined_units),
        format!("- Newly owned code bytes: {}", value.newly_assigned_code_bytes),
        format!(
            "- Trial retries: {} attempted, {} skipped as unchanged, {} units regenerated, {} budget exhausted",
            value.retry.attempted,
            value.retry.skipped_as_unchanged,
            value.retry.regenerated,
            value.retry.budget_exhausted
        ),
        format!("- Validation: `{}`", value.validation),
        String::new(),
        "This stage certifies only the newly selected ranges; pre-existing ownership is not \
         re-certified."
            .to_string(),
        String::new(),
        "## Separate progress metrics".to_string(),
        String::new(),
        "| Metric | Baseline | Final |".to_string(),
        "|---|---:|---:|".to_string(),
        format!(
            "| Represented source TUs | {} | {} |",
            value.metrics.representation.baseline_tus, value.metrics.representation.final_tus
        ),
        format!(
            "| Objdiff-matched code bytes | {} | {} |",
            value.metrics.objdiff_matching.baseline_code_bytes,
            value.metrics.objdiff_matching.final_code_bytes
        ),
        format!(
            "| Configured source-linked code bytes | {} | {} |",
            value.metrics.configured_source_linkage.baseline_code_bytes,
            value.metrics.configured_source_linkage.final_code_bytes
        ),
        "| Newly verified source-linked code bytes | 0 | 0 |".to_string(),
        String::new(),
    ];
    lines.push("## Translation-unit identifications".to_string());
    lines.push(String::new());
    lines.push(
        "Identification is reported independently of boundary certainty and application. A build \
         refusal does not erase the binary observation."
            .to_string(),
    );
    lines.push(String::new());
    lines.push(
        "| TU | Kind | Identity | Basis | Members | Boundary blockers | Application blockers |"
            .into(),
    );
    lines.push("|---|---|---|---|---:|---|---|".into());
    for identification in &value.identifications {
        lines.push(format!(
            "| `{}` | {} | `{}` | `{}` | {}/{} | {} | {} |",
            markdown_cell(&identification.unit),
            if identification.autogenerated { "autogenerated" } else { "source" },
            identification_confidence(identification.confidence),
            identification_basis(identification.basis),
            identification.matched_functions,
            identification.source_functions,
            blockers(&identification.boundary_blockers),
            blockers(&identification.application_blockers),
        ));
    }
    lines.push(String::new());
    lines.push("## Selected ranges".to_string());
    lines.push(String::new());
    if value.selected.is_empty() {
        lines.push("No range passed the coverage gates.".to_string());
    } else {
        lines.push("| TU | Evidence | Section | Range | Bytes |".to_string());
        lines.push("|---|---|---|---:|---:|".to_string());
        for (name, alternative) in &value.selected {
            lines.push(format!(
                "| `{name}` | `{}` | `{}` | `{}..{}` | {} |",
                alternative.evidence,
                alternative.section,
                alternative.start,
                alternative.end,
                alternative.covered_bytes
            ));
        }
    }
    if !value.transactions.is_empty() {
        lines.push(String::new());
        lines.push("## Ownership transactions".to_string());
        lines.push(String::new());
        lines.push(
            "In the order integration applied them. Each moves ownership for every unit it \
             names at once; a superseded one was later replaced for its candidate, and its \
             effect on any other unit stands unless a later transaction wrote that unit too."
                .to_string(),
        );
        lines.push(String::new());
        lines.push(
            "| Transaction | Candidate | Evidence | Effects | Net bytes | Superseded |".into(),
        );
        lines.push("|---|---|---|---|---:|---|".into());
        for transaction in &value.transactions {
            let effects: Vec<String> = transaction
                .members
                .iter()
                .map(|member| {
                    format!(
                        "`{}` +{} −{}",
                        markdown_cell(&member.unit),
                        member.gained_bytes,
                        member.lost_bytes
                    )
                })
                .collect();
            lines.push(format!(
                "| `{}` | `{}` | `{}` | {} | {} | {} |",
                short(&transaction.id),
                markdown_cell(&transaction.candidate),
                transaction.evidence,
                effects.join("<br>"),
                transaction.net_bytes,
                if transaction.superseded { "yes" } else { "no" }
            ));
        }
    }
    if !value.eligible_excluded_by_only.is_empty() {
        lines.push(String::new());
        lines.push("## Eligible candidates excluded by `--only`".to_string());
        lines.push(String::new());
        lines.extend(value.eligible_excluded_by_only.iter().map(|name| format!("- `{name}`")));
    }
    if !value.joint_run_diagnostics.is_empty() {
        lines.push(String::new());
        lines.push("## Joint runs unresolved at preparation".to_string());
        lines.push(String::new());
        let mut counts = BTreeMap::<&str, usize>::new();
        for diagnostic in &value.joint_run_diagnostics {
            *counts.entry(&diagnostic.reason).or_default() += 1;
        }
        lines.extend(counts.into_iter().map(|(reason, count)| format!("- {reason}: {count}")));
    }
    lines.push(String::new());
    lines.push("## Remaining dispositions".to_string());
    lines.push(String::new());
    let mut counts: BTreeMap<&str, usize> = BTreeMap::new();
    for disposition in value.dispositions.values() {
        *counts.entry(disposition.as_str()).or_default() += 1;
    }
    lines.extend(counts.iter().map(|(name, count)| format!("- {name}: {count}")));
    lines.extend(stunted_section(&value.stunted_splits));
    lines.join("\n") + "\n"
}

fn identification_confidence(value: IdentificationConfidence) -> &'static str {
    match value {
        IdentificationConfidence::Absent => "absent",
        IdentificationConfidence::Tentative => "tentative",
        IdentificationConfidence::Corroborated => "corroborated",
        IdentificationConfidence::Ambiguous => "ambiguous",
    }
}

fn identification_basis(value: crate::analysis::ownership::IdentificationBasis) -> &'static str {
    use crate::analysis::ownership::IdentificationBasis;
    match value {
        IdentificationBasis::None => "none",
        IdentificationBasis::NamesOnly => "names-only",
        IdentificationBasis::Binary => "binary",
        IdentificationBasis::Mixed => "mixed",
    }
}

fn blockers(values: &[String]) -> String {
    if values.is_empty() {
        "none".into()
    } else {
        values.iter().map(|value| markdown_cell(value)).collect::<Vec<_>>().join("<br>")
    }
}

fn markdown_cell(value: &str) -> String { value.replace('|', "\\|").replace(['\r', '\n'], " ") }

/// Reports units whose existing range is too small to be the whole unit.
///
/// These never appear as candidates: owning any range makes a unit
/// represented, so this stage skips it and discovery only extends what is
/// already there. The report is the only place they can surface at all.
fn stunted_section(stunted: &[Stunted]) -> Vec<String> {
    if stunted.is_empty() {
        return Vec::new();
    }
    let mut lines = vec![
        String::new(),
        "## Stunted splits".to_string(),
        String::new(),
        format!(
            "{} units claim less than half the bytes the same unit claims in the source \
             version. A range this small is usually built on a symbol that several source \
             objects define, so the two versions' linkers placed it in different units and \
             matching its name proved nothing about ownership.",
            stunted.len()
        ),
        String::new(),
        "These are **not** candidates: owning any range makes a unit represented, so no stage \
         looks for its real one while the fragment stands. Removing a fragment is only safe \
         when the unit's true range is separately determinable, which this audit does not \
         decide."
            .to_string(),
        String::new(),
        "| TU | Section | Claimed | Source version | Ratio |".to_string(),
        "|---|---|---:|---:|---:|".to_string(),
    ];
    for entry in stunted.iter().take(20) {
        lines.push(format!(
            "| `{}` | `{}` | {} | {} | {:.3} |",
            entry.unit, entry.section, entry.claimed_bytes, entry.expected_bytes, entry.ratio
        ));
    }
    if stunted.len() > 20 {
        lines.push(format!("\n…and {} more; see `coverage.json`.", stunted.len() - 20));
    }
    lines
}

