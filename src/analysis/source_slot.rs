//! A function identity can have a competing translation-unit placement.
//!
//! Two binary-supported functions of another unit can flank an apparently
//! independent match in the target while their source functions flank a
//! same-sized function in that other unit. This does not prove which object
//! emitted the target function. It does make the isolated match insufficient
//! as an ownership anchor until another observation distinguishes the slots.

use std::collections::{BTreeMap, BTreeSet};

use super::ownership::{
    IdentificationReport, SourceFunctionObservation, TargetFunctionObservation,
};

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct CompetingSourceSlot {
    pub foreign_unit: String,
    pub source_address: String,
    pub source_name: String,
    pub left_attribution_id: String,
    pub right_attribution_id: String,
}

fn address(text: &str) -> Option<u32> { u32::from_str_radix(text.strip_prefix("0x")?, 16).ok() }

fn size(start: &str, end: &str) -> Option<u32> {
    address(end)?.checked_sub(address(start)?).filter(|size| *size > 0)
}

/// Return identity matches with a complete, equally plausible source-order
/// slot in another unit. A slot is a veto, never a grant to the foreign unit.
pub fn competing_source_slots(
    report: &IdentificationReport,
) -> BTreeMap<String, CompetingSourceSlot> {
    let explicit_units: BTreeSet<&str> = report
        .units
        .iter()
        .filter(|unit| !unit.autogenerated)
        .map(|unit| unit.unit.as_str())
        .collect();
    let by_target: BTreeMap<_, _> = report
        .attributions
        .iter()
        .map(|item| {
            (
                (
                    item.target.module.as_str(),
                    item.target.section.as_str(),
                    item.target.address.as_str(),
                ),
                item,
            )
        })
        .collect();
    let mut sources: BTreeMap<_, Vec<&SourceFunctionObservation>> = BTreeMap::new();
    for function in &report.source_functions {
        sources
            .entry((function.unit.as_str(), function.module.as_str(), function.section.as_str()))
            .or_default()
            .push(function);
    }
    for functions in sources.values_mut() {
        functions.sort_by_key(|function| &function.address);
    }
    let mut targets: Vec<&TargetFunctionObservation> = report.target_functions.iter().collect();
    targets.sort_by_key(|function| (&function.module, &function.section, &function.address));
    let mut competing = BTreeMap::new();
    for window in targets.windows(3) {
        let [left, middle, right] = window else { unreachable!() };
        if !left.extent_known
            || !middle.extent_known
            || !right.extent_known
            || left.module != middle.module
            || left.section != middle.section
            || right.module != middle.module
            || right.section != middle.section
            || left.end != middle.address
            || middle.end != right.address
        {
            continue;
        }
        let get = |function: &TargetFunctionObservation| {
            by_target
                .get(&(
                    function.module.as_str(),
                    function.section.as_str(),
                    function.address.as_str(),
                ))
                .copied()
        };
        let (Some(candidate), Some(before), Some(after)) = (get(middle), get(left), get(right))
        else {
            continue;
        };
        let foreign = before.source.unit.as_str();
        if !candidate.independent
            || candidate.ambiguous
            || !candidate.binary_supported
            || candidate.source.unit == foreign
            || after.source.unit != foreign
            || [before, after].iter().any(|item| {
                item.ambiguous
                    || !item.binary_supported
                    || item.source_weak
                    || item.target_weak
                    || item.source.module != middle.module
                    || item.source.section != middle.section
            })
            || middle.current_owner.as_deref().is_some_and(|owner| owner != foreign)
            || !explicit_units.contains(foreign)
        {
            continue;
        }
        let Some(source) =
            sources.get(&(foreign, before.source.module.as_str(), before.source.section.as_str()))
        else {
            continue;
        };
        let Some(left_index) = source.iter().position(|function| {
            function.address == before.source.address && function.end == before.source.end
        }) else {
            continue;
        };
        let Some([slot, right_source]) = source.get(left_index + 1..left_index + 3) else {
            continue;
        };
        if !source[left_index].extent_known
            || !slot.extent_known
            || !right_source.extent_known
            || source[left_index].end != slot.address
            || slot.end != right_source.address
            || right_source.address != after.source.address
            || right_source.end != after.source.end
            || size(&slot.address, &slot.end) != size(&middle.address, &middle.end)
        {
            continue;
        }
        competing.insert(candidate.id.clone(), CompetingSourceSlot {
            foreign_unit: foreign.to_string(),
            source_address: slot.address.clone(),
            source_name: slot.name.clone(),
            left_attribution_id: before.id.clone(),
            right_attribution_id: after.id.clone(),
        });
    }
    competing
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::analysis::{
        matching::{MatchMethod, MatchTier},
        ownership::{
            AttributionOrigin, FunctionAttribution, FunctionLocation, SourceFunction,
            UnitIdentification,
        },
    };

    fn hex(address: u32) -> String { format!("0x{address:08X}") }

    fn attribution(
        unit: &str,
        name: &str,
        source: u32,
        target: u32,
        independent: bool,
    ) -> FunctionAttribution {
        FunctionAttribution {
            id: format!("{unit}:{target:08X}"),
            target: FunctionLocation {
                module: "main".into(),
                section: ".text".into(),
                address: hex(target),
                end: hex(target + 0x10),
            },
            source: SourceFunction {
                name: name.into(),
                unit: unit.into(),
                module: "main".into(),
                section: ".text".into(),
                address: hex(source),
                end: hex(source + 0x10),
            },
            method: MatchMethod::ExactHash,
            tier: MatchTier::Confident,
            confidence: 1.0,
            evidence_count: 1,
            origin: AttributionOrigin::NormalizedBody,
            distinctive_body: true,
            unique_exact_body: true,
            binary_supported: true,
            independent,
            ambiguous: false,
            competing: None,
            source_weak: false,
            target_weak: false,
            template_instantiation: false,
            current_target_owner: None,
            evidence: Vec::new(),
        }
    }

    fn report() -> IdentificationReport {
        let sources = [
            ("B.cpp", "before", 0x2000),
            ("B.cpp", "slot", 0x2010),
            ("B.cpp", "after", 0x2020),
            ("A.cpp", "same_body", 0x3000),
        ];
        IdentificationReport {
            schema: 19,
            source: String::new(),
            target: String::new(),
            unattributed_references: Vec::new(),
            unmatched_source_references: Vec::new(),
            local_data_pairs: Vec::new(),
            vtable_pairs: Vec::new(),
            attributions: vec![
                attribution("B.cpp", "before", 0x2000, 0x1000, false),
                attribution("A.cpp", "same_body", 0x3000, 0x1010, true),
                attribution("B.cpp", "after", 0x2020, 0x1020, false),
            ],
            source_functions: sources
                .into_iter()
                .map(|(unit, name, address)| SourceFunctionObservation {
                    name: name.into(),
                    unit: unit.into(),
                    module: "main".into(),
                    section: ".text".into(),
                    address: hex(address),
                    end: hex(address + 0x10),
                    extent_known: true,
                    normalized_body_sha256: None,
                    weak: false,
                    callers: Vec::new(),
                })
                .collect(),
            target_functions: [0x1000, 0x1010, 0x1020]
                .into_iter()
                .map(|address| TargetFunctionObservation {
                    name: String::new(),
                    module: "main".into(),
                    section: ".text".into(),
                    address: hex(address),
                    end: hex(address + 0x10),
                    extent_known: true,
                    current_owner: None,
                    owner_autogenerated: false,
                    callers: Vec::new(),
                    normalized_body_sha256: None,
                    weak: false,
                })
                .collect(),
            helper_families: Vec::new(),
            unresolved_target_clusters: Vec::new(),
            helper_tail_hypotheses: Vec::new(),
            object_evidence: None,
            units: vec![
                UnitIdentification::absent("A.cpp", 1),
                UnitIdentification::absent("B.cpp", 3),
            ],
        }
    }

    #[test]
    fn a_foreign_source_slot_with_binary_supported_flanks_vetoes_identity_as_owner() {
        let report = report();
        let found = competing_source_slots(&report);
        let slot = &found["A.cpp:00001010"];
        assert_eq!(slot.foreign_unit, "B.cpp");
        assert_eq!(slot.source_address, "0x00002010");
        assert_eq!(slot.left_attribution_id, "B.cpp:00001000");
        assert_eq!(slot.right_attribution_id, "B.cpp:00001020");
    }

    #[test]
    fn a_disrupted_slot_or_weak_flank_does_not_veto_the_match() {
        let mut broken = report();
        broken.source_functions[1].end = hex(0x201C);
        assert!(competing_source_slots(&broken).is_empty());

        let mut unsupported = report();
        unsupported.attributions[2].binary_supported = false;
        assert!(competing_source_slots(&unsupported).is_empty());

        let mut owned = report();
        owned.target_functions[1].current_owner = Some("A.cpp".into());
        assert!(competing_source_slots(&owned).is_empty());

        let mut autogenerated = report();
        autogenerated.units[1].autogenerated = true;
        assert!(competing_source_slots(&autogenerated).is_empty());
    }
}
