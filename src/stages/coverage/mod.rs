    /// A result whose history applied each accepted candidate's selection once,
    /// in order.
    fn stage_result(accepted: Vec<Candidate>, selections: Selections) -> crate::run::StageResult {
        let applied = accepted
            .iter()
            .filter_map(|candidate| {
                let id = selections.get(&candidate.name)?;
                let alternative = proposal_of(candidate)
                    .unwrap()
                    .alternatives
                    .into_iter()
                    .find(|a| &a.id == id)?;
                Some(applied_entry(&candidate.name, &alternative))
            })
            .collect();
        crate::run::StageResult {
            stage: "coverage".into(),
            offered: accepted.clone(),
            accepted,
            deferred: Vec::new(),
            selections,
            events: Vec::new(),
            validation: VALIDATION.into(),
            dol_sha1: String::new(),
            baseline: Default::default(),
            final_measures: Default::default(),
            reserved_by_earlier_stage: Vec::new(),
            eligible_excluded_by_only: Vec::new(),
            applied,
            retry: Default::default(),
            seconds: 0.0,
        }
    }

    fn applied_entry(unit: &str, alternative: &Alternative) -> Applied {
        Applied {
            unit: unit.into(),
            id: alternative.id.clone(),
            units: alternative.transaction.writes().map(str::to_string).collect(),
            record: serde_json::to_value(AppliedRecord {
                observation: observation_reference(),
                alternative: alternative.clone(),
                unit_extracts: BTreeMap::new(),
            })
            .unwrap(),
        }
    }

